#!/usr/bin/env python3
"""Write <Root>/<Dir>/Complete/Value.lean for a token whose dispatcher has no check of the value
(`dispatch.value_check = per_function`): each function checks CALLVALUE itself, so a run that
ends with no error has value 0, for every selector of the table. The case of a path function is
its generated value-revert path `<fn>_p0`; the case of a function of `readonly_loops` is a block
lemma written here for the entry of the function (JUMPDEST CALLVALUE ISZERO PUSH2 JUMPI PUSH1 0
DUP1 REVERT), after the generated `ok_<fn>Entry`.

Usage: gen_value.py <config/token.json>"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402


def cap(s):
    return s[0].upper() + s[1:]


def main():
    tok = tokenlib.load()
    gen = os.path.join(tok.lean_dir, 'Gen')
    fns = [f for f in tok.funcs] + [f for f in tok.prefixes]
    by = {f['index']: f for f in fns}
    loops = {f['index']: f for f in tok.loops}
    o = ['import %s.Gen\nimport %s.Gen.Loops\n\n' % (tok.mod, tok.mod),
         '/-!\n# Every function of %s rejects a call that carries value\n\n' % tok.name,
         'Generated by `scripts/gen_value.py`; do not edit. Lean checks every statement against\n'
         '`CODE`.\n\nThe dispatcher of this code has no check of the value: each function checks '
         'CALLVALUE\nitself. `value_zero_of_ok`: a run of `CODE` from pc 0 that ends with no error '
         'has value 0, for\nevery selector of the table.\n-/\n\n',
         'set_option autoImplicit false\nset_option linter.unusedVariables false\n'
         'set_option maxRecDepth 4096\n\n',
         'namespace %s.Complete\n\nopen UsdtVerify\nopen TokenKit TokenKit.Complete\nopen %s\n\n' % (tok.root, tok.root),
         'open EthLib.Base (Fork U256)\nopen EthLib.Execution\nopen EthLib.Execution.Evm\n'
         'open EthLib.Execution.Evm.Logic\nopen GasCosts\n\n',
         'variable {fork : Fork} {message : Message fork}\n\n',
         'open %s.Blocks %s.Paths %s.Complete UsdtVerify.Complete UsdtVerify.Gas\n\n' % ((tok.root,) * 3),
         'variable {state : State.TransactionState} {substate : Substate}\n\n',
         'variable {bound : Nat} {runChild : MessageRunner fork Nat bound}\n\n']
    for f in tok.loops:
        fn = f['name']
        src = open(os.path.join(gen, 'P%sEntry.lean' % cap(fn))).read()
        pc = int(re.search(r'\(At CODE message (\d+) \[\(BitVec', src.split('theorem %sEntry_p0' % fn)[1]).group(1))
        # WBTC local: Solidity 0.4.24 keeps the value on the stack (CALLVALUE DUP1 ISZERO)
        dup = tok.code[pc + 2] == 0x80
        k = 1 if dup else 0
        G = 28 if dup else 25
        o.append('/-- The entry of `%s` (pc %d) with a nonzero value: REVERT. -/\n' % (fn, pc))
        o.append('theorem %s_value {rest : List U256} {mem : ByteArray} {gas : Nat}\n'
                 '    (hfork : .berlin ≤ fork) (hc : (isZero message.value) = 0)\n'
                 '    (hrest : rest.length ≤ 900) (hg : %d ≤ gas) :\n'
                 '    Logic.SpecG fork (At CODE message %d (rest) mem gas state substate)\n'
                 '      (Halted true ByteArray.empty (gas - %d) state substate) := by\n'
                 '  step jumpdestR\n'
                 '  step Gas.callvalueG (by code_fact) (by code_fact) (by gas_ok) (by stk_ok)\n'
                 % (fn, G, pc, G)
                 + ('  step dupR 0\n' if dup else '') +
                 '  step unR 0x15 instruction_iszero\n'
                 '  step pushR 2 (%d : U256)\n  at_pc %d\n  step jumpi0R hc\n'
                 '  step pushR 1 (0 : U256)\n  at_pc %d\n  step dupR 0\n'
                 '  step Gas.reshapeG (g\' := gas - %d) rfl rfl (by gas_ok)\n'
                 '  exact specL (revert0K hfork (by code_fact) (by code_fact))\n\n'
                 % (int(tok.code[pc + 4 + k:pc + 6 + k].hex(), 16), pc + 6 + k, pc + 9 + k, G))
    o.append('/-- From Berlin, a run of `CODE` from pc 0 that ends with no error has value 0: every\n'
             'function of the table rejects a call that carries value. -/\n'
             'theorem value_zero_of_ok (hfork : .berlin ≤ fork)\n'
             '    (hsize\' : message.data.size < 2 ^ 256)\n'
             '    {gas : Nat} {evm s : Evm fork Nat}\n'
             '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
             '    (hrun : EndsL runChild evm s) (hok : s.error = none) :\n'
             '    message.value = 0 := by\n'
             '  obtain ⟨hsize, i, hi⟩ := ends_ok_dispatch hfork hsize\' start hrun hok\n'
             '  refine Classical.byContradiction fun hv => ?_\n'
             '  have hc : (isZero message.value) = 0 := isZero_eq_zero_iff.mpr hv\n'
             '  match i, hi with\n')
    nt = len(tok.table)
    for i in range(nt):
        sel = tok.table[i][0]
        o.append('  | ⟨%d, _⟩, hi =>\n    have h : selector message.data = 0x%08x := hi\n' % (i, sel))
        if i in by:
            fn = by[i]['name']
            src = open(os.path.join(gen, 'P%s.lean' % cap(fn))).read()
            body = src.split('theorem %s_p0' % fn)[1].split(':= by')[0]
            assert '(hc1 : (isZero message.value) = 0)' in body and 'Halted true' in body, fn
            b = int(re.search(r'\(hg : (\d+) ≤ gas\)', body).group(1))
            o.append('    exact no_okLE (B := %d) (fun g hg => %s_p0 hfork hsize hsize\' h hc (by omega))\n'
                     '      (fun _ e h => reverted_error e h) start hrun hok\n' % (b, fn))
        else:
            fn = loops[i]['name']
            o.append('    obtain ⟨-, z, hz, hzr⟩ := ok_%sEntry hfork hsize\' h start hrun hok\n'
                     '    exact no_okLE (B := 28) (fun g hg => %s_value hfork hc (by simp) hg)\n'
                     '      (fun _ e h => reverted_error e h) hz hzr hok\n' % (fn, fn))
    o.append('  | ⟨n + %d, hn⟩, _ => exact absurd hn (by omega)\n\nend %s.Complete\n' % (nt, tok.root))
    open(os.path.join(tok.lean_dir, 'Complete', 'Value.lean'), 'w').write(''.join(o))
    print('Complete/Value.lean:', nt, 'selectors')


main()
