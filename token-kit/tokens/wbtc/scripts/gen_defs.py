c5, _ = split_eq(hyp("tac_call", "hc_ic_some"))
code = hyp("tac_call", "hcode")
TV = {"F": "(tacF message)", "N": "(tacN message)", "W": "(tacW message)"}


def tv(t):
    return re.sub(r"\b([FNW])\b", lambda m: TV[m.group(1)], t)


