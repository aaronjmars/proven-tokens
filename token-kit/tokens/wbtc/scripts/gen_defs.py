"""Writes LinkVerify/Link/Tac/Defs.lean: the conditions of the paths of transferAndCall and the
names of their ends, with the terms taken from the generated paths (the file info.json that
gen_tac.py writes), so that they are the terms of the generated theorems."""
import json, re, sys

info = json.load(open(sys.argv[1]))
paths = open(sys.argv[2] + "/Paths.lean").read()
MASK = "(1461501637330902918203684832716283019655932542975 : U256)"


def hyp(p, h):
    return dict(info["path:" + p]["hyps"])[h]


def split_eq(t):
    for op in (" ≠ 0", " = 0"):
        if t.endswith(op):
            return t[: -len(op)], op
    raise ValueError(t)


def body(n):
    return re.search(r"^def %s .*?:=\n  (.*?)\n\n" % n, paths, re.S | re.M).group(1)


def args(t):
    """The head and the arguments of an application `(f a b c)`."""
    assert t[0] == "(" and t[-1] == ")", t[:40]
    t = t[1:-1]
    out, depth, cur = [], 0, ""
    for ch in t:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == " " and depth == 0:
            if cur:
                out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur:
        out.append(cur)
    return out


c1, _ = split_eq(hyp("tac_call", "hc1_vr_ok"))
c2, _ = split_eq(hyp("tac_call", "hc2_vr_ok"))
c3, _ = split_eq(hyp("tac_call", "hc3_xf1"))
