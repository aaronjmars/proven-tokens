#!/usr/bin/env python3
"""Write <Root>/<Dir>/Gen/Loops.lean: for each function of `readonly_loops` in the configuration
(a function whose code loops, such as name() and symbol() that copy a string), the theorem
`ro_<fn>`: a run with the selector of `<fn>` that ends with no error writes no storage word and
adds no log (`Ro`, TokenKit/Evm/Safe.lean of the kit).

The script does not follow paths (a loop has no bound). It cuts the code reachable from the entry
of the function into blocks, and keeps of the stack at the start of a block only the words that
are the same constant on every way in (the return addresses); every other word, the memory, the
gas, the state and the substate are unknown.

- `<fn>_s<pc>`: the block at `pc`. A run that ends with no error from the start of the block
  goes through the start of a next block (one, or one of two after a JUMPI), with less gas and a
  state that differs by reads only; or the block halts (RETURN, REVERT) and the end state
  differs from the state at the block by reads only.
- `<fn>_safe_<pc>`: from the start of the block at `pc`, the end state of a run that ends with no
  error differs by reads only. For a block outside every loop, from the lemmas of the next
  blocks. For the head of a loop, by induction on the gas: each turn of the loop uses gas.
- `ro_<fn>`: from pc 0, through the dispatcher (`enter`).

The script stops on an opcode it has no rule for (SSTORE, LOG, CALL and the like: the function
is then not read-only by this argument), on a jump to a word that is not a constant, and on a
loop with two ways in or a loop inside a loop.

In the mode `walk` of the dispatcher (code compiled with the optimizer; the logic mode, see
TokenKit/Evm/SafeL.lean): the runs are `EndsL`, the rules are lifted to `Logic.StepG`, the way in
is the path `<fn>Entry` that gen_paths.py writes (from pc 0 to the entry of the table, through
`ok_<fn>Entry`), and a block is kept once for each set of constants on its stack, so a helper
that two places call (with two return addresses) gives two lemmas `<fn>_s<pc>_<k>`. SHL, SHR,
SLT, SGT, OR and XOR have a rule there (`bin3L`).

Nothing the script computes is trusted: Lean checks every lemma against `CODE`.

Usage: gen_loops.py <config/token.json>"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402
from disasm import disasm  # noqa: E402

BIN = {0x01: 'instruction_add', 0x02: '(instruction_of_stackOnlyStep rfl)', 0x03: 'instruction_sub',
       0x04: '(instruction_of_stackOnlyStep rfl)', 0x10: '(instruction_of_stackOnlyStep rfl)',
       0x11: '(instruction_of_stackOnlyStep rfl)', 0x14: 'instruction_eq',
       0x16: '(instruction_of_stackOnlyStep rfl)'}
UN = {0x15: 'instruction_iszero', 0x19: '(instruction_of_stackOnlyStep rfl)'}
CF = '(by code_fact) (by code_fact)'
STK = '(by first | exact Nat.le_of_ble_eq_true rfl | stk_ok)'
OLD = '(Nat.le_trans (by decide) hfork)'

BIN3 = (0x12, 0x13, 0x17, 0x18, 0x1b, 0x1c)

HEAD = """{IMPORTS}

/-!
# The functions of {TOKEN} that loop only read

Generated by `scripts/gen_loops.py` from the runtime bytecode; do not edit. Lean checks every
statement against `CODE`.

- `ro_<fn>`: a run of `CODE` from pc 0 with the selector of `<fn>` that ends with no error
  leaves every storage word as it was and adds no log (`Ro`, TokenKit/Evm/Safe.lean). It says
  nothing of the bytes returned.
- `<fn>_s<pc>`: one block of the code of `<fn>`, with the stack unknown but for the constants
  shown. `<fn>_safe_<pc>`: the same claim as `ro_<fn>` from the start of that block; at the head
  of a loop it is proved by induction on the gas.
-/

set_option autoImplicit false
set_option linter.unusedVariables false
set_option maxRecDepth 4096

namespace {ROOT}.Loops

open UsdtVerify
open TokenKit
open {ROOT} {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic
open GasCosts

variable {{fork : Fork}} {{message : Message fork}}
{VARS}
"""


class Stop(Exception):
    pass


class Loops:
    def __init__(self, tok):
        self.tok = tok
        self.ins = {pc: (op, name, arg) for pc, op, name, arg in disasm(tok.code)}
        self.ctx = tok.walk        # a block for each set of constants on its stack
        self.lg = tok.logic        # runs `EndsL`, rules lifted to Logic.StepG
        self.ENDS = 'EndsL runChild' if self.lg else 'Ends fork'
        self.SAFE = 'SafeL' if self.lg else 'Safe'
        self.minfork = tok.cfg.get('min_fork')
        self.berlin = '(toBerlin hfork)' if self.minfork else 'hfork'
        self.envl = bool(tok.cfg.get('paths', {}).get('env_local'))

    # a node is a pc (one block for each pc) or, in the mode `walk`, a pc with the stack shape
    def pcof(self, n):
        return n[0] if self.ctx else n

    def lab(self, n):
        if not self.ctx:
            return str(n)
        same = sorted((m for m in self.shapes if m[0] == n[0]), key=lambda m: self.order[m])
        return str(n[0]) if len(same) == 1 else f'{n[0]}_{same.index(n)}'

    def node(self, t, st):
        return (t, tuple(st)) if self.ctx else t

    def blk(self, n):
        """`block` of the node `n`, with the nodes of the next blocks in the end."""
        steps, end, st = self.block(self.pcof(n), self.shapes[n])
        if end[0] != 'halt':
            end = (end[0],) + tuple(self.node(t, st) for t in end[1:])
        return steps, end, st

    def nodes(self):
        if self.ctx:
            return sorted(self.shapes, key=lambda n: (n[0], self.order[n]))
        return sorted(self.shapes)

    def lift(self, rule, halt=False):
        if not self.lg:
            return rule
        return f'{"specL" if halt else "hoareL"} ({rule})'

    # ---------------------------------------------------------------- one block

    def block(self, pc0, shape):
        """Run the block at pc0 on the abstract stack `shape` (top first; an int is a constant,
        None an unknown word). Returns (steps, end, stack): steps are (rule, next pc, strict);
        end is ('halt', rule) | ('jump', pc) | ('jumpi', taken, fall) | ('fall', pc)."""
        st = list(shape)
        steps = []
        pc = pc0

        def need(n):
            if len(st) < n:
                raise Stop(f'pc {pc}: the stack of the block at {pc0} is too short')

        while True:
            op, name, arg = self.ins[pc]
            if op == 0x5b and pc != pc0:
                return steps, ('fall', pc), st
            nxt = pc + 1
            if op == 0x5b:
                rule = f'Gas.jumpdestG {CF} hG'
            elif op == 0x50:
                need(1)
                st.pop(0)
                rule = f'Gas.popG {CF} hG'
            elif 0x60 <= op <= 0x7f:
                n = op - 0x5f
                w = int(arg, 16)
                st.insert(0, w)
                nxt = pc + 1 + n
                rule = (f'Gas.pushG (n := {n}) (word := ({w} : U256)) (by decide) {CF} '
                        f'(decode_push {n} (by decide)) (by code_fact) hG {STK}')
            elif 0x80 <= op <= 0x8f:
                k = op - 0x80
                need(k + 1)
                st.insert(0, st[k])
                rule = f'Gas.dupG {k} {CF} rfl hG {STK}'
            elif 0x90 <= op <= 0x9f:
                k = op - 0x8f
                need(k + 1)
                st[0], st[k] = st[k], st[0]
                rule = f'swap{k}K {CF} hG'
            elif op in BIN:
                need(2)
                st[0:2] = [None]
                rule = (f'Gas.binaryG (byte := 0x{op:02x}) {CF} '
                        f'(ofByte_of_decode rfl (Fork.frontier_le _)) {BIN[op]} hG')
            elif op in BIN3 and self.lg:
                need(2)
                st[0:2] = [None]
                rule = (f'!bin3L (byte := 0x{op:02x}) {CF} rfl {OLD} '
                        f'(instruction_of_stackOnlyStep rfl) rfl hG')
            elif op == 0x36 and self.lg:
                st.insert(0, None)
                rule = f'Gas.calldatasizeG {CF} hG {STK}'
            elif op == 0x35 and self.lg:
                need(1)
                st[0] = None
                rule = f'Gas.calldataloadG {CF} hG'
            elif op in UN:
                need(1)
                st[0] = None
                rule = (f'Gas.unaryG (byte := 0x{op:02x}) {CF} '
                        f'(ofByte_of_decode rfl (Fork.frontier_le _)) {UN[op]} hG')
            elif op == 0x0a:
                need(2)
                st[0:2] = [None]
                rule = f'Gas.expLG {OLD} {CF} hG'
            elif op == 0x34:
                st.insert(0, None)
                rule = f'Gas.callvalueG {CF} hG {STK}'
            elif op == 0x33:
                st.insert(0, None)
                rule = f'Gas.callerG {CF} hG {STK}'
            elif op == 0x51:
                need(1)
                st[0] = None
                rule = f'Gas.mloadG {CF} hG'
            elif op == 0x52:
                need(2)
                del st[0:2]
                rule = f'Gas.mstoreG {CF} hG'
            elif op == 0x20:
                need(2)
                st[0:2] = [None]
                rule = f'Gas.keccak256G {CF} hG'
            elif op == 0x5f and self.lg and self.minfork:
                # PUSH0 (`min_fork`; rule `push0L`)
                st.insert(0, 0)
                rule = f'!push0L hfork {CF} hG {STK}'
            elif op == 0x37 and self.lg and self.envl:
                # CALLDATACOPY (`paths.env_local`: rule `calldatacopyL` of a module of
                # `paths.block_imports`)
                need(3)
                del st[0:3]
                rule = f'!calldatacopyL {CF} hG'
            elif op == 0x46 and self.lg and self.envl:
                # CHAINID (rule `chainidL`)
                st.insert(0, None)
                rule = f'!chainidL {self.berlin} {CF} hG {STK}'
            elif op == 0x30 and self.lg and self.envl:
                # ADDRESS (`addressL`, TokenKit/Evm/Logic.lean)
                st.insert(0, None)
                rule = f'!addressL {CF} hG {STK}'
            elif op == 0x54:
                need(1)
                st[0] = None
                rule = f'sloadK {self.berlin} {CF} hG'
            elif op == 0x56:
                need(1)
                d = st.pop(0)
                if d is None:
                    raise Stop(f'pc {pc}: JUMP to a word that is not a constant')
                steps.append((self.lift(f'Gas.jumpG {CF} hG (by valid_dest)'), d, False))
                return steps, ('jump', d), st
            elif op == 0x57:
                need(2)
                d = st.pop(0)
                st.pop(0)
                if d is None:
                    raise Stop(f'pc {pc}: JUMPI to a word that is not a constant')
                return steps, ('jumpi', d, pc + 1), st
            elif op == 0xf3:
                need(2)
                return steps, ('halt', self.lift(f'Gas.returnG {CF} hG', True)), st
            elif op == 0xfd:
                need(2)
                return steps, ('halt', self.lift(f'Gas.revertG {OLD} {CF} hG', True)), st
            else:
                raise Stop(f'pc {pc}: no read-only rule for {name}')
            rule = rule[1:] if rule[0] == '!' else self.lift(rule)
            steps.append((rule, nxt, op == 0x5b and pc == pc0))
            pc = nxt

    # ---------------------------------------------------------------- the blocks of a function

    def analyse_ctx(self, entry, depth):
        """Mode `walk`: every (pc, stack shape) reachable from the entry; no meet."""
        start = (entry, tuple([None] * depth))
        self.shapes = shapes = {start: list(start[1])}
        self.order = {start: 0}
        todo = [start]
        while todo:
            n = todo.pop()
            _, end, st = self.block(n[0], shapes[n])
            for t in end[1:] if end[0] != 'halt' else []:
                m = (t, tuple(st))
                if m not in shapes:
                    if len(shapes) > 2000:
                        raise Stop('more than 2000 blocks: a loop that changes the constants')
                    shapes[m] = list(st)
                    self.order[m] = len(self.order)
                    todo.append(m)
        return shapes

    def analyse(self, entry):
        """Fixpoint of the stack shapes: shapes[pc] is the meet of the stacks on every way in."""
        shapes = {entry: [None]}
        todo = [entry]
        while todo:
            pc = todo.pop()
            _, end, st = self.block(pc, shapes[pc])
            for t in end[1:] if end[0] != 'halt' else []:
                if t not in shapes:
                    shapes[t] = list(st)
                    todo.append(t)
                    continue
                old = shapes[t]
                if len(old) != len(st):
                    raise Stop(f'block {t}: two stack heights ({len(old)}, {len(st)})')
                new = [a if a == b else None for a, b in zip(old, st)]
                if new != old:
                    shapes[t] = new
                    todo.append(t)
        return shapes

    @staticmethod
    def sccs(nodes, succ):
        """Tarjan; the components come out with every successor component first."""
        index, low, on, stack, out = {}, {}, set(), [], []
        counter = [0]

        def visit(v):
            work = [(v, iter(succ[v]))]
            index[v] = low[v] = counter[0]
            counter[0] += 1
            stack.append(v)
            on.add(v)
            while work:
                node, it = work[-1]
                done = True
                for w in it:
                    if w not in index:
                        index[w] = low[w] = counter[0]
                        counter[0] += 1
                        stack.append(w)
                        on.add(w)
                        work.append((w, iter(succ[w])))
                        done = False
                        break
                    if w in on:
                        low[node] = min(low[node], index[w])
                if done:
                    work.pop()
                    if work:
                        low[work[-1][0]] = min(low[work[-1][0]], low[node])
                    if low[node] == index[node]:
                        comp = []
                        while True:
                            w = stack.pop()
                            on.discard(w)
                            comp.append(w)
                            if w == node:
                                break
                        out.append(comp)

        for v in nodes:
            if v not in index:
                visit(v)
        return out

    # ---------------------------------------------------------------- Lean text

    @staticmethod
    def stack_term(shape, v):
        return '[' + ', '.join(f'({a} : U256)' if a is not None else f'{v}{i}'
                               for i, a in enumerate(shape)) + ']'

    @staticmethod
    def vars_of(shape, v):
        return [f'{v}{i}' for i, a in enumerate(shape) if a is None]

    def post(self, fn, t, strict):
        sh = self.shapes[t]
        ys = self.vars_of(sh, 'y')
        b = (f'({" ".join(ys)} : U256) ' if ys else '')
        return (f"(∃ {b}(mem' : ByteArray) (g' : Nat) (S' : State.TransactionState) "
                f"(ss' : Substate)\n        (l' : Evm fork Nat), "
                f"At CODE message {self.pcof(t)} {self.stack_term(sh, 'y')} mem' g' S' ss' l' ∧\n"
                f"        {self.ENDS} l' s ∧ g' {'<' if strict else '≤'} g ∧ "
                f"Ro message.currentTarget S ss S' ss')")

    def binders(self, shape):
        xs = self.vars_of(shape, 'x')
        return ((f'{{{" ".join(xs)} : U256}} ' if xs else '') +
                '{mem : ByteArray} {g : Nat} {S : State.TransactionState} {ss : Substate}\n'
                '    {l s : Evm fork Nat}')

    def seg(self, fn, pc):
        sh = self.shapes[pc]
        steps, end, st = self.blk(pc)
        strict = bool(steps) and steps[0][2]
        self.strict[pc] = strict
        if end[0] == 'halt':
            concl = 'Ro message.currentTarget S ss s.state s.substate'
        elif end[0] == 'jumpi':
            concl = self.post(fn, end[1], strict) + ' ∨\n      ' + self.post(fn, end[2], strict)
        else:
            concl = self.post(fn, end[1], strict)
        o = [f'theorem {fn}_s{self.lab(pc)} (hfork : .berlin ≤ fork) {self.binders(sh)}\n'
             f'    (h0 : At CODE message {self.pcof(pc)} {self.stack_term(sh, "x")} mem g S ss l)\n'
             f'    (e0 : {self.ENDS} l s) (hok : s.error = none) :\n      {concl} := by']
        k = 0
        for rule, nxt, st1 in steps:
            last = '-' if not st1 else f'hs{k + 1}'
            o.append(f'  obtain ⟨g{k + 1}, l{k + 1}, h{k + 1}, e{k + 1}, hg{k + 1}, {last}⟩ := '
                     f"{self.SAFE}.stepE (pc' := {nxt}) h{k} e{k} hok\n"
                     f'    (fun G hG => {rule}) (by decide)')
            if k:
                o.append(f'  clear h{k} e{k}')
            k += 1

        def give(t):
            n = len(self.vars_of(self.shapes[t], 'y')) + 5
            return '⟨' + ', '.join(['_'] * n) + f', h{k}, e{k}, by omega, by ro_reads⟩'

        if end[0] == 'halt':
            o.append(f'  obtain ⟨hst, hss⟩ := {self.SAFE}.haltE h{k} e{k} hok (fun G hG => {end[1]})')
            o.append('  rw [hst, hss]')
            o.append('  ro_reads')
        elif end[0] == 'jumpi':
            o.append(f'  rcases {self.SAFE}.jumpiE (pcT := {self.pcof(end[1])}) (pcF := {self.pcof(end[2])}) h{k} e{k} hok {CF}\n'
                     f'      (by valid_dest) (by decide) (by decide) with\n'
                     f'    ⟨g{k + 1}, l{k + 1}, h{k + 1}, e{k + 1}, hg{k + 1}⟩ | '
                     f'⟨g{k + 1}, l{k + 1}, h{k + 1}, e{k + 1}, hg{k + 1}⟩')
            k += 1
            o.append(f'  · exact .inl {give(end[1])}')
            o.append(f'  · exact .inr {give(end[2])}')
        else:
            o.append(f'  exact {give(end[1])}')
        return '\n'.join(o) + '\n\n', len(steps)

    def safe(self, fn, comp):
        """The theorem `<fn>_safe_<pc>` of the entry block of a component."""
        inside = set(comp)
        loop = len(comp) > 1 or comp[0] in self.succ[comp[0]]
        if loop:
            heads = [b for b in comp
                     if b == self.entry or any(b in self.succ[a] for a in self.succ
                                               if a not in inside)]
            if len(heads) != 1:
                raise Stop(f'the loop of the blocks {sorted(self.lab(x) for x in comp) if self.ctx else sorted(comp)} has {len(heads)} ways in')
            head = heads[0]
            if not self.strict[head]:
                raise Stop(f'the head {head} of a loop does not start with JUMPDEST')
        else:
            head = comp[0]
        sh = self.shapes[head]
        xs = self.vars_of(sh, 'x')
        o = [f'theorem {fn}_safe_{self.lab(head)} (hfork : .berlin ≤ fork) : ∀ (g : Nat) '
             f'{self.binders(sh).replace("{g : Nat} ", "")},\n'
             f'    At CODE message {self.pcof(head)} {self.stack_term(sh, "x")} mem g S ss l → '
             f'{self.ENDS} l s → s.error = none →\n'
             f'    Ro message.currentTarget S ss s.state s.substate := by',
             '  intro g']
        names = ' '.join(xs + ['mem', 'S', 'ss', 'l', 's', 'h0', 'e0', 'hok'])
        if loop:
            o += ['  induction g using Nat.strongRecOn with', '  | ind g ih =>',
                  f'    intro {names}']
            pad0 = '    '
        else:
            o.append(f'  intro {names}')
            pad0 = '  '
        count = [0]

        def chain(ros, x):
            for r in reversed(ros):
                x = f'{r}.trans ({x})'
            return x

        def body(b, hk, ros, pad, path):
            """Lines that close the goal from the block `b` with the hypotheses h<hk>, e<hk>."""
            end = self.blk(b)[1]
            call = f'{fn}_s{self.lab(b)} hfork h{hk} e{hk} hok'
            if end[0] == 'halt':
                return [f'{pad}exact {chain(ros, call)}']

            def pat(t):
                count[0] += 1
                k = count[0]
                ys = [f'y{k}_{i}' for i, a in enumerate(self.shapes[t]) if a is None]
                return k, ('⟨' + ', '.join(ys + [f'mem{k}', f'g{k}', f'S{k}', f'ss{k}', f'l{k}',
                                                 f'h{k}', f'e{k}', f'hg{k}', f'r{k}']) + '⟩')

            def cont(t, k, pad):
                ros2 = ros + [f'r{k}']
                if loop and t == head:
                    return [f'{pad}exact ' + chain(ros2, f'ih g{k} (by omega) h{k} e{k} hok')]
                if t in inside:
                    if t in path:
                        raise Stop(f'a loop inside the loop of head {head} (block {t})')
                    return body(t, k, ros2, pad, path + [t])
                return [f'{pad}exact ' + chain(ros2, f'{fn}_safe_{self.lab(t)} hfork _ h{k} e{k} hok')]

            if end[0] == 'jumpi':
                k1, p1 = pat(end[1])
                k2, p2 = pat(end[2])
                out = [f'{pad}rcases {call} with\n{pad}  {p1} |\n{pad}  {p2}']
                for t, k in ((end[1], k1), (end[2], k2)):
                    sub = cont(t, k, pad + '  ')
                    out.append(f'{pad}· ' + sub[0].lstrip())
                    out += sub[1:]
                return out
            k1, p1 = pat(end[1])
            return [f'{pad}obtain {p1} := {call}'] + cont(end[1], k1, pad)

        o += body(head, 0, [], pad0, [head])
        return '\n'.join(o) + '\n\n'

    def function(self, f):
        fn = f['name']
        self.entry = f['dest']
        if self.ctx:
            # the path `<fn>Entry` of gen_paths.py: from pc 0 to the entry of the table
            ent = json.load(open(self.tok.paths_json))[fn + 'Entry']['paths']
            at = [p for p in ent if p['kind'] == 'at']
            if len(at) != 1 or any(p['kind'] == 'ok' for p in ent):
                raise Stop('the way in is not one path')
            self.analyse_ctx(self.entry, len(at[0]['stack']))
            self.entry = (self.entry, tuple([None] * len(at[0]['stack'])))
        else:
            self.shapes = self.analyse(self.entry)
        self.strict = {}
        self.succ = {}
        for pc in self.shapes:
            end = self.blk(pc)[1]
            self.succ[pc] = [] if end[0] == 'halt' else list(dict.fromkeys(end[1:]))
        o, n_ins = [], 0
        for pc in self.nodes():
            text, n = self.seg(fn, pc)
            o.append(text)
            n_ins += n
        comps = self.sccs(self.nodes(), self.succ)
        loops = [c for c in comps if len(c) > 1 or c[0] in self.succ[c[0]]]
        for comp in comps:
            o.append(self.safe(fn, comp))
        if self.ctx:
            pat = ', '.join([cn for (cn, _, _) in at[0]['conds']] + ['-', 'z', 'hz', 'hzr'])
            o.append(
                f'/-- A run of `CODE` from pc 0 with the selector of `{f["sig"]}` that ends with '
                f'no error\nonly reads: every storage word is as before and no log is added. -/\n'
                f'theorem ro_{fn} (hfork : .berlin ≤ fork)\n'
                f"    (hsize' : message.data.size < 2 ^ 256)\n"
                f'    (hsel : selector message.data = 0x{f["selector"]:08x})\n'
                f'    {{state : State.TransactionState}} {{substate : Substate}}\n'
                f'    {{gas : Nat}} {{evm s : Evm fork Nat}}\n'
                f'    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                f'    (hrun : {self.ENDS} evm s) (hok : s.error = none) :\n'
                f'    Ro message.currentTarget state substate s.state s.substate := by\n'
                f"  obtain ⟨{pat}⟩ := Paths.ok_{fn}Entry hfork hsize' hsel start hrun hok\n"
                f'  exact {fn}_safe_{self.lab(self.entry)} hfork _ hz hzr hok\n\n')
            return ''.join(o), dict(function=fn, blocks=len(self.shapes), instructions=n_ins,
                                    loops=[sorted(self.lab(x) for x in c) for c in loops])
        N = self.tok.prelude_gas + self.tok.entry_gas * (f['index'] + 1)
        nt = len(self.tok.table)
        o.append(
            f'/-- A run of `CODE` from pc 0 with the selector of `{f["sig"]}` that ends with no '
            f'error\nonly reads: every storage word is as before and no log is added. -/\n'
            f'theorem ro_{fn} (hfork : .berlin ≤ fork)\n'
            + ('    (hsize : 4 ≤ message.data.size)\n' if self.tok.explicit_size else '') +
            f"    (hsize' : message.data.size < 2 ^ 256)\n"
            f'    (hsel : selector message.data = 0x{f["selector"]:08x})\n'
            f'    {{state : State.TransactionState}} {{substate : Substate}}\n'
            f'    {{gas : Nat}} {{evm s : Evm fork Nat}}\n'
            f'    (start : At CODE message 0 [] .empty gas state substate evm)\n'
            f'    (hrun : Ends fork evm s) (hok : s.error = none) :\n'
            f'    Ro message.currentTarget state substate s.state s.substate := by\n'
            + ('' if self.tok.explicit_size else
               "  " + self.tok.cfg['dispatch'].get(
                   'size_proof',
                   "obtain ⟨hsize, -, -⟩ := ends_ok_dispatch hfork hsize' start hrun hok") + "\n") +
            f"  obtain ⟨g1, l1, h1, e1, -, -⟩ := Safe.stepE (pc' := {f['dest']}) start hrun hok\n"
            f"    (fun G hG => enter hsize hsize' ⟨{f['index']}, by decide⟩ "
            f'(key := 0x{f["selector"]:08x}) (dest := {f["dest"]})\n'
            f'      (N := {N}) (by decide) (by decide) (by decide) hsel hG) rfl\n'
            f'  exact {fn}_safe_{f["dest"]} hfork _ h1 e1 hok\n\n')
        return ''.join(o), dict(function=fn, blocks=len(self.shapes), instructions=n_ins,
                                loops=[sorted(c) for c in loops])


def main():
    tok = tokenlib.load()
    if not tok.loops:
        print('no readonly_loops in the configuration')
        return
    g = Loops(tok)
    if tok.walk:
        imports = '\n'.join([f'import {tok.mod}.Complete.Dispatch']
                            + [f'import {tok.mod}.Gen.P{f["name"][0].upper()}{f["name"][1:]}Entry'
                               for f in tok.loops] + ['import TokenKit.Evm.SafeL']
                            + ([f'import {m}' for m in tok.cfg.get('paths', {}).get('block_imports', [])]
                               if tok.cfg.get('paths', {}).get('env_local') else []))
    else:
        imports = (f'import {tok.mod}.Complete.Dispatch\nimport {tok.mod}.Enter\n'
                   'import TokenKit.Evm.Safe')
    lvars = ('variable {bound : Nat} {runChild : MessageRunner fork Nat bound}\n'
             if tok.logic else '')
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, TOKEN=tok.name, IMPORTS=imports, VARS=lvars)]
    for f in tok.loops:
        try:
            text, info = g.function(f)
        except Stop as e:
            sys.exit(f'{f["name"]}: {e}')
        o.append(text)
        print(info)
    o.append(f'end {tok.root}.Loops\n')
    os.makedirs(os.path.join(tok.lean_dir, 'Gen'), exist_ok=True)
    open(os.path.join(tok.lean_dir, 'Gen', 'Loops.lean'), 'w').write(''.join(o))
    print('Gen/Loops.lean:', len(tok.loops), 'functions')


main()
