#!/usr/bin/env python3
"""Write <Root>/<Dir>/Code/Bytes.lean (the runtime bytecode as one hexadecimal natural number)
and <Root>/Test/Hash.lean (the build-time check that the embedded bytes and their Keccak-256
hash are those of the fetched file), from the bytecode file named in the configuration.

Usage: gen_code.py <config/token.json>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402
from keccak import keccak256  # noqa: E402

HASH = """import {MOD}.Code
import EthLib.Execution.Evm.Instructions.Keccak

/-!
# Test: the embedded bytecode is the fetched one

Generated by `scripts/gen_code.py` from `{HEX}`; do not edit.

The build runs these checks; a failing check is an error of the build.

They are tests, run by the interpreter, not theorems.

- The bytes of `CODE` are the bytes of `{HEX}`.
- The Keccak-256 hash of `CODE` is the hash recorded in `data/SOURCE.md`.
-/

namespace {ROOT}.Test

open EthLib.Execution.Evm

/-- The Keccak-256 hash of the runtime bytecode, from `scripts/keccak.py`. -/
def EXPECTED_HASH : String := "{HASHHEX}"

/-- Lowercase hexadecimal of a list of bytes. -/
def hexOf (bytes : List UInt8) : String :=
  String.join (bytes.map fun b =>
    let d := fun (n : Nat) => if n < 10 then Char.ofNat (48 + n) else Char.ofNat (87 + n)
    String.ofList [d (b.toNat / 16), d (b.toNat % 16)])

#eval show IO Unit from do
  let hex ← IO.FS.readFile "{HEX}"
  let expected := hex.trimAscii.toString
  let got := hexOf CODE.toList
  unless got == expected do
    throw (IO.userError "CODE differs from {HEX}")
  unless CODE.size == {SIZE} do
    throw (IO.userError "CODE has the wrong size")
  let h := hexOf (EthLib.Base.U256.toBeBytes (keccak CODE)).toList
  unless h == EXPECTED_HASH do
    throw (IO.userError s!"keccak256 of CODE is {{h}}")
  IO.println s!"CODE: {{CODE.size}} bytes, keccak256 {{h}}"

end {ROOT}.Test
"""


def main():
    tok = tokenlib.load()
    hexs = tok.code.hex()
    size = len(tok.code)
    rel = tok.cfg['hex']
    out = [f"-- Generated by scripts/gen_code.py from {rel}; do not edit.",
           "",
           "/-!",
           "# The bytes of the runtime bytecode",
           "",
           f"Defines `CODE_NAT`, the runtime bytecode of {tok.name} as one natural number, and `CODE_SIZE`, its",
           f"number of bytes; `{tok.dir}/Code.lean` turns them into the byte array `CODE`.",
           "-/",
           "",
           f"namespace {tok.root}",
           "",
           f"/-- The runtime bytecode of {tok.name} as one big-endian natural number. -/",
           "def CODE_NAT : Nat :=",
           "  0x" + hexs,
           "", "/-- The number of bytes of the runtime bytecode. -/",
           f"def CODE_SIZE : Nat := {size}", "", f"end {tok.root}", ""]
    os.makedirs(os.path.join(tok.lean_dir, 'Code'), exist_ok=True)
    open(os.path.join(tok.lean_dir, 'Code', 'Bytes.lean'), 'w').write("\n".join(out))
    os.makedirs(os.path.join(tok.root_dir, tok.root, 'Test'), exist_ok=True)
    open(os.path.join(tok.root_dir, tok.root, 'Test', 'Hash.lean'), 'w').write(HASH.format(
        MOD=tok.mod, ROOT=tok.root, HEX=rel, SIZE=size, HASHHEX=keccak256(tok.code).hex()))
    print('Code/Bytes.lean and Test/Hash.lean:', size, 'bytes, keccak256', keccak256(tok.code).hex())


main()
