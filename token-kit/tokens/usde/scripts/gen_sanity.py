OFFS = {4: 1, 36: 2, 68: 3, 100: 4}


def sexp(text):
    """The term as nested lists of atoms."""
    toks = re.findall(r'[()]|[^\s()]+', text)
    pos = 0

    def rd():
        nonlocal pos
        t = toks[pos]
        pos += 1
        if t != '(':
            return t
        out = []
        while toks[pos] != ')':
            out.append(rd())
        pos += 1
        return out
    return rd()


def norm_reads(t):
    """As `simp only [storageAt_readSlot]`: drop the reads right under a `storageAt`."""
    if not isinstance(t, list):
        return t
    t = [norm_reads(x) for x in t]
    if t and t[0] == 'storageAt':
        while isinstance(t[1], list) and t[1][0] == 'readSlot':
            t[1] = t[1][1]
    return t


class Words:
    """Proof terms for the conditions of a path on a state whose words are 0 or 5, with every
    amount 1 (lemmas of Evm/Witness2.lean). `nk` is the number of slots that hold 5."""

    def __init__(self, keys, args):
        self.keys = [sexp(k if k.startswith('(') else '(' + k + ')') for k in keys]
        self.args = args

    def key(self, k):
        """The fact `hk<i>` of the slot `k` of the path, by its text."""
        def inst(t):
            if t == 'message.caller.toU256':
                return 'caller.toU256'
            if not isinstance(t, list):
                return t
            if t[:2] == ['loadWord', 'message.data']:
                return [str(self.args[OFFS[int(t[2])] - 1]), ':', 'U256']
            return [inst(x) for x in t]
        return 'hk%d' % (self.keys.index(inst(k)) + 1)

    def eq5(self, x):
        assert x[0] == 'storageAt' and x[1] == 'state', x
        return self.key(x[3])

    def bd(self, S):
        if S == 'state':
            return 'hle'
        if S[0] == 'readSlot':
            return f'(Witness.bd_read {self.bd(S[1])} _ _)'
        assert S[0] == 'writeSlot', S
        return f'(Witness.bd_write (by supply_side) {self.bd(S[1])} {self.vle(S[4])})'

    def pos(self, S, k):
        if S == 'state':
            return f'(Witness.pos_of_eq5 {self.key(k)})'
        if S[0] == 'readSlot':
            return f'(Witness.pos_read {self.pos(S[1], k)} _ _)'
        assert S[0] == 'writeSlot', S
        return f'(Witness.pos_write (by supply_side) {self.pos(S[1], k)} {self.vpos(S[4])})'

    def vle(self, v):
        assert v[0] == 'sub', v
        return f'(Witness.sub_le5 {self.eq5(v[1])})'

    def vpos(self, v):
        if v[0] == 'sub':
            return f'(Witness.sub_pos {self.eq5(v[1])})'
        assert v[0] == 'add', v
        return f'(Witness.add_pos ({self.bd(v[1][1])} _))'

    def proof(self, c, taken):
        t = norm_reads(sexp(c))
        n = 0
        while t[0] == 'isZero':
            t, n = t[1], n + 1
        if taken and n == 1 and t[0] == 'lessThan' and t[1][0] == 'storageAt':
            return f'Witness.ge_ok {self.eq5(t[1])}'
        if n in (1, 2) and t[0] == 'lessThan' and t[1][0] == 'add' and taken == (n == 1):
            return f'Witness.noov{n} _ ({self.bd(t[1][1][1])} _)'
        if taken and n == 1 and t[0] == 'greaterThan':
            return f'Witness.gt_ok {self.eq5(t[2])}'
        if taken and n == 3 and t[0] == 'greaterThan':
            return f'Witness.gt3_ok {self.pos(t[2][1], t[2][3])}'
        sys.exit('no proof for the shape of ' + c[:120])


def cond_proof(c, args, has_caller_hyp, words=None, taken=True, given=None):
    if given:
        return given
    if words is not None and 'storageAt' in c:
        used = [OFFS[int(k)] for k in sorted(set(re.findall(r'loadWord message\.data (\d+) 32', c)),
                                             key=int)]
        rw = 'rw [' + ', '.join(f'hA{i}' for i in used) + ']\n      ' if used else ''
        return (f'(by\n      {rw}try simp only [storageAt_readSlot]\n'
                f'      exact {words.proof(c, taken)})')
    if words is not None and 'message.caller' not in c and c != '(isZero message.value)':
        used = [OFFS[int(k)] for k in sorted(set(re.findall(r'loadWord message\.data (\d+) 32', c)),
                                             key=int)]
        if used:
            return '(by rw [' + ', '.join(f'hA{i}' for i in used) + ']; decide)'
    return cond_proof0(c, args, has_caller_hyp, taken)


def cond_proof0(c, args, has_caller_hyp, taken=True):
    """The proof term of one condition of the path, by its shape. A lemma of Evm/Witness.lean
    proves a condition that is not 0: for a condition that is 0 only `decide` is used."""
    r = cond_shape(c, args, has_caller_hyp)
    if not taken and 'decide' not in r:
        sys.exit('no proof for a condition that is 0: ' + c[:120])
    return r


def cond_shape(c, args, has_caller_hyp):
    used = [OFFS[int(k)] for k in sorted(set(re.findall(r'loadWord message\.data (\d+) 32', c)),
                                         key=int)]
    rw = 'rw [' + ', '.join(f'hA{i}' for i in used) + ']; ' if used else ''
    if c == '(isZero message.value)':
        return '(by rw [hval]; decide)'
    if c.startswith('(isZero (lessThan (sub (BitVec.ofNat 256 message.data.size) (4 : U256)) ('):
        return '(by rw [hsz]; decide)'
    if c == f'(isZero (isZero (isZero (equal (bitwiseAnd {MASK} message.caller.toU256) (0 : U256)))))':
        return '(Witness.ne3 _ hcal)'
    if c.startswith('(isZero (isZero (isZero (equal ') and c.endswith('(0 : U256)))))') and used:
        return f'(by {rw}decide)'
    m = re.match(r'\(isZero \(isZero \(isZero \(greaterThan \(loadWord message\.data (\d+) 32\) ', c)
    if m and args[OFFS[int(m.group(1))] - 1] == 0:
        return f'(by {rw}exact Witness.nogt _)'
    m = re.search(r' \(loadWord message\.data (\d+) 32\)\) ', c)
    if c.startswith('(isZero (isZero (isZero (lessThan (add ') and m and \
            args[OFFS[int(m.group(1))] - 1] == 0:
        return f'(by {rw}exact Witness.nolt _)'
    m = re.match(r'\(isZero \(greaterThan \(loadWord message\.data (\d+) 32\) ', c)
    if m and args[OFFS[int(m.group(1))] - 1] == 0:
        return f'(by {rw}exact Witness.nogt1 _)'
    m = re.match(r'\(isZero \(isZero \(isZero \(lessThan \(storageAt .* '
                 r'\(loadWord message\.data (\d+) 32\)\)\)\)\)$', c)
    if m and args[OFFS[int(m.group(1))] - 1] == 0:
        # `require(balance >= amount)` of solc 0.4 with the amount 0
        return f'(by {rw}exact Witness.nolt0 _)'
    sys.exit('no proof for the shape of ' + c[:120])


def short_witness(fn, p):
    """The witness of the fallback with no call data."""
    msg = f'(m_{fn} b t C caller)'
    sub = lambda t: re.sub(r'\bsubstate\b', 'ss', re.sub(
        r'\bstate\b', '(sState C [])', re.sub(r'\bmessage\b', msg, t)))
    return (f'/-- The call with no call data from `caller` to `C`. -/\n'
            f'abbrev m_{fn} (b : BlockEnvironment fork) (t : TransactionEnvironment fork)\n'
            f'    (C caller : Address) : Message fork :=\n'
            f'  sMsg b t C caller CODE ByteArray.empty\n\n'
            f'/-- The success path `{p["name"]}` is not empty: this call runs to the end with '
            f'no error. -/\n'
            f'theorem {fn}_runs (hfork : .berlin ≤ fork) (b : BlockEnvironment fork)\n'
            f'    (t : TransactionEnvironment fork) (C caller : Address) (ss : Substate) :\n'
            f'    ∃ (gas : Nat) (evm s : Evm fork Nat),\n'
            f'      At CODE {msg} 0 [] .empty gas (sState C []) ss evm ∧\n'
            f'      Ends fork evm s ∧ s.error = none ∧\n'
            f'      s.output = {sub(p["out"])} := by\n'
            f'  have hspec := {p["name"]} (fork := fork) (message := {msg})\n'
            f'    (state := sState C []) (substate := ss)\n'
            f'    hfork (show ByteArray.empty.size < 4 by decide) rfl (hasAccount_sState C []) (Nat.lt_succ_self _)\n'
            f'  obtain ⟨s, hr, hrun, hH⟩ := hspec (sFrame {msg} (sState C []) ss _)\n'
            f'    (at_sFrame _ rfl _ _ _)\n'
            f'  refine ⟨_, _, s, at_sFrame _ rfl _ _ _, Or.inl ⟨reaches_toStep hr, hrun⟩, ?_, '
            f'hH.2.2.1⟩\n'
            f'  obtain ⟨-, he, -⟩ := hH\n'
            f'  simpa using he\n\n')


def witness_eval(o, f, fn, sel, p, ent, tag, first, logic):
    """The form `eval` (see the head of the file); returns 1."""
    args = ent['args']
    caller = ent.get('caller', 'Witness.CALLER1')
    cw = ent.get('caller_word', 'Witness.CALLER1W')
    cwp = ent.get('caller_proof', 'Witness.caller1_toU256')
    ST = '(sState C [' + ', '.join(f'({str(k).replace("MASK", MASK)}, {v})'
                                   for k, v in ent.get('slots', [])) + '])'
    na = len(args)
    bs = ', '.join('0x%02x' % b for b in sel.to_bytes(4, 'big'))
    S = f'SEL_{fn}'
    data = S if na == 0 else f'(data{na} {S} ' + ' '.join(str(a) for a in args) + ')'
    msg = f'(m_{tag} b t C)'
    sub = lambda t: re.sub(r'\bsubstate\b', 'ss', re.sub(
        r'\bstate\b', ST, re.sub(r'\bmessage\b', msg, t)))
    if first:
        o.append(f'/-- The four bytes of the selector of `{f["sig"]}`. -/\n'
                 f'def {S} : ByteArray := ⟨#[{bs}]⟩\n\n'
                 f'theorem size_{S} : {S}.size = 4 := by decide\n\n')
    o.append(f'/-- The call `{fn}({", ".join(str(a) for a in args)})` from `{caller}` to `C`. -/\n'
             f'abbrev m_{tag} (b : BlockEnvironment fork) (t : TransactionEnvironment fork)\n'
             f'    (C : Address) : Message fork :=\n'
             f'  sMsg b t C {caller} CODE {data}\n\n')
    ends = ('(∀ {bound : Nat} (runChild : MessageRunner fork Nat bound),\n'
            '        GasMeter.gasHeld evm.gas ≤ bound → EndsL runChild evm s)' if logic
            else 'Ends fork evm s')
    o.append('set_option maxHeartbeats 1000000 in\n')
    o.append(f'/-- The success path `{p["name"]}` is not empty: this call runs to the end with '
             f'no error. -/\n'
             f'theorem {tag}_runs (hfork : .berlin ≤ fork) (b : BlockEnvironment fork)\n'
             f'    (t : TransactionEnvironment fork) (C : Address) (ss : Substate) :\n'
             f'    ∃ (gas : Nat) (evm s : Evm fork Nat),\n'
             f'      At CODE {msg} 0 [] .empty gas {ST} ss evm ∧\n'
             f'      {ends} ∧ s.error = none ∧\n'
             f'      s.output = {sub(p["out"])} ∧\n'
             f'      s.state = {sub(p["state"])} := by\n')
    L = [f'have hdata : {msg}.data = {data[1:-1] if na else data} := rfl']
    if na:
        L.append(f'have hsz : {msg}.data.size = {4 + 32 * na} := by\n'
                 f'    rw [hdata]; exact size_data{na} size_{S} ' + ' '.join(['_'] * na))
        L.append(f'have hsl : selector {msg}.data = selector {S} := by\n'
                 f'    rw [hdata]; exact selector_data{na} size_{S} ' + ' '.join(['_'] * na))
    else:
        L.append(f'have hsz : {msg}.data.size = 4 := size_{S}')
        L.append(f'have hsl : selector {msg}.data = selector {S} := rfl')
    for i in range(na):
        L.append(f'have hA{i + 1} : loadWord {msg}.data {4 + 32 * i} 32 = {args[i]} := by\n'
                 f'    rw [hdata]; exact Witness.arg{i + 1}_data{na} size_{S} '
                 + ' '.join(['_'] * na))
    L.append(f'have hval : {msg}.value = 0 := rfl')
    L.append(f'have hcw : {msg}.caller.toU256 = {cw} := {cwp}')
    L.append(f'have hct : {msg}.currentTarget = C := rfl')
    L.append(f'have hacc : hasAccount {ST} C := hasAccount_sState C _')
    rules = ', '.join(['hval', 'hsz'] + [f'hA{i + 1}' for i in range(na)] +
                      ['hcw', 'hct', 'storageAt_readSlot', 'Readable.storageAt_writeSlot_ite',
                       'storageAt_sState_cons', 'storageAt_sState_nil'])
    cond = ('(by\n      simp (disch := supply_side) only\n'
            f'        [{rules}]\n      <;> decide +kernel)')
    call = ['hfork', '(by rw [hsz]; decide)', '(by rw [hsz]; decide)', '(by rw [hsl]; decide)']
    if p['wrote']:
        call += ['rfl', 'hacc']
    call += [ent.get('proofs', {}).get(c[0], cond) for c in p['conds']]
    call.append('(Nat.lt_succ_self _)' if p['wrote'] else '(Nat.le_refl _)')
    L.append(f'have hspec := {p["name"]} (fork := fork) (message := {msg})\n'
             f'    (state := {ST[1:-1]}) (substate := ss)\n    '
             + '\n    '.join(call))
    L.append(f'obtain ⟨s, hr, hrun, hH⟩ := hspec (sFrame {msg} {ST} ss _)\n'
             '    (at_sFrame _ rfl _ _ _)')
    run = ('fun rc within => Witness.endsL_of_reaches hr hrun rc within' if logic
           else 'Or.inl ⟨reaches_toStep hr, hrun⟩')
    L.append(f'refine ⟨_, _, s, at_sFrame _ rfl _ _ _, {run}, ?_,\n'
             '    hH.2.2.1, hH.2.2.2.2.1⟩')
    L.append('obtain ⟨-, he, -⟩ := hH')
    L.append('simpa using he')
    o.append('\n'.join('  ' + x for x in L) + '\n\n')
    return 1


def witness(o, f, fn, fb, sel, p, args, tag, first, logic=False):
    """Append the witness of the success path `p` of `fn` (theorem `<tag>_runs`); returns 1."""
    if isinstance(args, dict) and 'slots' in args:
        return witness_eval(o, f, fn, sel, p, args, tag, first, logic)
    words, given, keys = None, {}, []
    if isinstance(args, dict):
        keys = [k.replace('MASK', MASK) for k in args.get('state', [])]
        given = args.get('proofs', {})
        args = args['args']
        words = Words(keys, args)
    ST = '(sState C [' + ', '.join(f'({k}, 5)' for k in keys) + '])'
    na = len(args)
    bs = ', '.join('0x%02x' % b for b in sel.to_bytes(4, 'big'))
    S = f'SEL_{fn}'
    data = S if na == 0 else f'(data{na} {S} ' + ' '.join(str(a) for a in args) + ')'
    if fb == 'short':
        o.append(short_witness(fn, p))
        return 1
    msg = f'(m_{tag} b t C caller)'
    need_caller = any('message.caller' in c[1] and 'equal' in c[1] for c in p['conds'])
    sub = lambda t: re.sub(r'\bsubstate\b', 'ss', re.sub(
        r'\bstate\b', ST, re.sub(r'\bmessage\b', msg, t)))
    if first:
        o.append(f'/-- The four bytes of the selector of `{f["sig"]}`. -/\n'
                 f'def {S} : ByteArray := ⟨#[{bs}]⟩\n\n'
                 f'theorem size_{S} : {S}.size = 4 := by decide\n\n')
    o.append(f'/-- The call `{fn}({", ".join(str(a) for a in args)})` from `caller` to `C`. -/\n'
             f'abbrev m_{tag} (b : BlockEnvironment fork) (t : TransactionEnvironment fork)\n'
             f'    (C caller : Address) : Message fork :=\n'
             f'  sMsg b t C caller CODE {data}\n\n')
    o.append(f'/-- The success path `{p["name"]}` is not empty: this call runs to the end with '
             f'no error. -/\n'
             f'theorem {tag}_runs (hfork : .berlin ≤ fork) (b : BlockEnvironment fork)\n'
             f'    (t : TransactionEnvironment fork) (C caller : Address) (ss : Substate)'
             + (f'\n    (hcal : bitwiseAnd {MASK} caller.toU256 ≠ 0)' if need_caller else '')
             + ' :\n'
             f'    ∃ (gas : Nat) (evm s : Evm fork Nat),\n'
             f'      At CODE {msg} 0 [] .empty gas {ST} ss evm ∧\n'
             f'      Ends fork evm s ∧ s.error = none ∧\n'
             f'      s.output = {sub(p["out"])} := by\n')
    L = [f'have hdata : {msg}.data = {data[1:-1] if na else data} := rfl']
    if na:
        L.append(f'have hsz : {msg}.data.size = {4 + 32 * na} := by\n'
                 f'    rw [hdata]; exact size_data{na} size_{S} ' + ' '.join(['_'] * na))
        L.append(f'have hsl : selector {msg}.data = selector {S} := by\n'
                 f'    rw [hdata]; exact selector_data{na} size_{S} ' + ' '.join(['_'] * na))
    else:
        L.append(f'have hsz : {msg}.data.size = 4 := size_{S}')
        L.append(f'have hsl : selector {msg}.data = selector {S} := rfl')
    for i in range(na):
        L.append(f'have hA{i + 1} : loadWord {msg}.data {4 + 32 * i} 32 = {args[i]} := by\n'
                 f'    rw [hdata]; exact Witness.arg{i + 1}_data{na} size_{S} '
                 + ' '.join(['_'] * na))
    L.append(f'have hval : {msg}.value = 0 := rfl')
    if fb:
        L.pop()  # a fallback takes any value
    if words is not None:
        L.append(f'have hacc : hasAccount {ST} C := hasAccount_sState C _')
        for i, k in enumerate(keys):
            L.append(f'have hk{i + 1} : storageAt {ST} C ({k}) = 5 := by\n'
                     '    simp only [storageAt_sState_cons, storageAt_sState_nil, eq_self, '
                     '↓reduceIte, ite_self]')
        L.append(f'have hle : ∀ n, (storageAt {ST} C n).toNat ≤ 5 := by\n'
                 '    intro n\n'
                 '    simp only [storageAt_sState_cons, storageAt_sState_nil]\n'
                 "    repeat' split\n"
                 '    all_goals decide')
    call = ['hfork', '(by rw [hsz]; decide)', '(by rw [hsz]; decide)', '(by rw [hsl]; decide)']
    if p['wrote']:
        call += ['rfl', '(hasAccount_sState C [])' if words is None else 'hacc']
    call += [cond_proof(c[1], args, need_caller, words, c[2], given.get(c[0]))
             for c in p['conds']]
    call.append('(Nat.lt_succ_self _)' if p['wrote'] else '(Nat.le_refl _)')
    L.append(f'have hspec := {p["name"]} (fork := fork) (message := {msg})\n'
             f'    (state := {ST[1:-1]}) (substate := ss)\n    '
             + '\n    '.join(call))
    L.append(f'obtain ⟨s, hr, hrun, hH⟩ := hspec (sFrame {msg} {ST} ss _)\n'
             '    (at_sFrame _ rfl _ _ _)')
    L.append('refine ⟨_, _, s, at_sFrame _ rfl _ _ _, Or.inl ⟨reaches_toStep hr, hrun⟩, ?_, '
             'hH.2.2.1⟩')
    L.append('obtain ⟨-, he, -⟩ := hH')
    L.append('simpa using he')
    o.append('\n'.join('  ' + x for x in L) + '\n\n')
    return 1


def main():
    tok = tokenlib.load()
    d = json.load(open(tok.paths_json))
    san = tok.cfg['sanity']
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, TOKEN=tok.name, doc=san.get('doc', DOC),
                     imports=''.join('\nimport ' + x for x in san.get('imports', [])))]
    n = 0
    for f in tok.funcs + [dict(x, fb=x['kind']) for x in tok.fallbacks]:
        fn, fb = f['name'], f.get('fb')
        # a fallback: no call data, or four bytes that are no selector of the table
        sel = f['selector'] if not fb else 0xffffffff
        if fb == 'other':
            assert all(k != sel for k, _ in tok.table)
            f = dict(f, sig='(no function: the fallback)')
        oks = [p for p in d[fn]['paths'] if p['kind'] == 'ok']
        if not oks:
            # a function whose path stops at a CALL (`"frame": true`) or at a pc of `stops`
            # has no success path in one frame: no generated witness
            print('no success path in one frame for', fn, '(no generated witness: write it by hand)',
                  file=sys.stderr)
            continue
        if not fb and fn not in san:
            print('no sanity entry for', fn, '(write its witness by hand)', file=sys.stderr)
            continue
        entry = san[fn] if not fb else []
        if isinstance(entry, dict) and 'args' not in entry:
            # {path name: words}: a witness for each success path named
            todo = [(p, entry[p['name']], p['name']) for p in oks if p['name'] in entry]
        elif len(oks) != 1:
            print(f'  {fn}: {len(oks)} success paths, witness by hand', file=sys.stderr)
            continue
        else:
            todo = [(oks[0], entry, fn)]
        for k, (p, args, tag) in enumerate(todo):
            n += witness(o, f, fn, fb, sel, p, args, tag, k == 0, tok.logic)
    o.append(f'end {tok.root}.Sanity\n')
    os.makedirs(os.path.join(tok.lean_dir, 'Sanity'), exist_ok=True)
    open(os.path.join(tok.lean_dir, 'Sanity', san.get('file', 'Zero') + '.lean'), 'w').write(''.join(o))
    print('Sanity/' + san.get('file', 'Zero') + '.lean:', n, 'witnesses')


main()
