#!/usr/bin/env python3
"""Write <Root>/<Dir>/Sanity/Zero.lean: for the success path of each function, one concrete call
on one concrete state where every hypothesis of the path theorem holds and the run ends with no
error. So no success path theorem is empty.

The state has one account, at the contract, and every slot 0. The call comes from any caller
whose address word is not 0 (`Witness.CALLER1` is one). The argument words come from the
configuration (`sanity.<fn>`, one word per argument): address arguments not 0, amounts 0, so
every SafeMath check passes whatever the storage holds.

Forms of `sanity.<fn>`:

- a list: the argument words, on the state with every slot 0 (the only success path);
- `{"args": [...], "state": [...], "proofs": {...}}`: the argument words, the slots that hold
  the word 5 (every amount is then 1; lemmas of Evm/Witness2.lean), and proofs given by hand
  for some conditions;
- `{path name: words}`: a function with several success paths, one witness `<path>_runs` for
  each path named.

- `{"args": [...], "slots": [[key, word], ...]}` (alone, or as the words of a path name): the
  form `eval`, for any shape of condition. The state holds the given words at the given slots
  (terms of Lean; `MASK` stands for the mask of an address), the caller is `Witness.CALLER1`
  (or `"caller"` with its word `"caller_word"`), and every condition of the path is computed:
  the argument words, the caller and the reads of storage are rewritten to closed terms, then
  the kernel decides (it computes the keccak of each mapping slot). The witness also states
  the end state. For a token in the logic mode the run is a run of the loop of the
  interpreter, for every message runner and bound.

A function with no entry, with no success path, or with several success paths and a plain list
is skipped (its witness is hand-written). A payable fallback (`fallbacks` of the configuration)
gets a witness with no call data (`short`) or with four bytes that are no selector (`other`).
`sanity.imports`, `sanity.doc` and `sanity.file` change the imports, the text and the name of
the file.

Each condition of the path is discharged by its shape (no value, enough call data, an address
that is not 0, a SafeMath check with the amount 0). A condition of another shape stops the
generator: write that witness by hand, as Sanity/Moves.lean.

Usage: gen_sanity.py <config/token.json>"""
