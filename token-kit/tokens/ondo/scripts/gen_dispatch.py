#!/usr/bin/env python3
"""Write the dispatcher files of a token from its runtime bytecode and its configuration:
<Root>/<Dir>/Code.lean, Steps.lean, Map.lean, Enter.lean, Spec/Dispatch.lean and
Complete/Dispatch.lean. They were written by hand for SHIB (12 entries); here the size of the
selector table, its keys and destinations, the free memory pointer, the fallback position and
the shape of the nonpayable check are read from the bytes.

The script runs only for a configuration with `"dispatch": {"generate": true, ...}`, so a token
whose dispatcher files are hand-written keeps them.

The dispatcher shape it knows (solc 0.4.x and 0.5.x without the optimizer; it stops on any other):

    PUSH1 fp PUSH1 0x40 MSTORE PUSH1 4 CALLDATASIZE LT PUSH2 fb JUMPI
    PUSH1 0 CALLDATALOAD PUSH29 2^224 SWAP1 DIV PUSH4 0xffffffff AND
    N times: DUP1 PUSH4 key EQ PUSH2 dest JUMPI
    fb: JUMPDEST PUSH1 0 DUP1 REVERT
    every dest: JUMPDEST CALLVALUE [DUP1] ISZERO PUSH2 ok JUMPI PUSH1 0 DUP1 REVERT

With `"dispatch": {"generate": true, "mode": "walk"}` (code compiled with the optimizer: a
callvalue check before the table, SHR for the selector, a table split by GT comparisons) the
script reads no shape at all. It writes Code.lean and Steps.lean as above, Map.lean with the
list `ENTRIES` only (every `DUP1 PUSH4 key EQ PUSH2 dest JUMPI` of the bytes, in order), and
Complete/Dispatch.lean, where the completeness of the dispatcher is proved from the `ok_`
theorems of the three fallbacks that gen_paths.py walks from pc 0 (`fallbacks` of kind `value`,
`short` and `other`; all three must be in the configuration: a dispatcher whose value check is
not before the table is not covered). There is no Enter.lean and no Spec/Dispatch.lean: the
route from pc 0 to a function is part of each path theorem.

Nothing the script computes is trusted: Lean checks every statement against `CODE`.

Usage: gen_dispatch.py <config/token.json>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402


def shape(tok):
    """Read the dispatcher off the bytes; stop if it is not the known shape."""
    c = tok.code

    def want(pos, hexs, what):
        b = bytes.fromhex(hexs)
        if c[pos:pos + len(b)] != b:
            raise SystemExit(f'dispatcher: {what} expected at {pos}, found {c[pos:pos + len(b)].hex()}')

    want(0, '60', 'PUSH1 fp')
    fp = c[1]
    want(2, '604052', 'PUSH1 0x40 MSTORE')
    want(5, '6004361061', 'PUSH1 4 CALLDATASIZE LT PUSH2')
    fb = int.from_bytes(c[10:12], 'big')
    want(12, '57', 'JUMPI')
    want(13, '6000357c01' + '00' * 28 + '900463ffffffff16', 'the selector computation')
    start = 54
    n = len(tok.table)
    for i in range(n):
        want(start + 11 * i, '8063', f'table entry {i}')
    if start + 11 * n != fb:
        raise SystemExit(f'dispatcher: the table ends at {start + 11 * n}, the fallback is at {fb}')
    want(fb, '5b600080fd', 'the fallback JUMPDEST PUSH1 0 DUP1 REVERT')
    dups = set()
    for _, d in tok.table:
        want(d, '5b34', f'JUMPDEST CALLVALUE at entry {d}')
        dup = c[d + 2] == 0x80
        dups.add(dup)
        k = d + 2 + (1 if dup else 0)
        want(k, '1561', f'ISZERO PUSH2 at entry {d}')
        want(k + 4, '57600080fd', f'JUMPI PUSH1 0 DUP1 REVERT at entry {d}')
    if len(dups) != 1:
        raise SystemExit('dispatcher: the entries do not share one nonpayable shape')
    dup = dups.pop()
    return dict(fp=fp, fb=fb, start=start, n=n, dup=dup, value_gas=28 if dup else 25)


