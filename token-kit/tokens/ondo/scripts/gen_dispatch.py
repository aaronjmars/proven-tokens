def walk_mode(tok, d):
    """Mode `walk`: no shape is read; see the head of this file."""
    kinds = {f['kind']: f['name'] for f in tok.fallbacks}
    for k in ('value', 'short', 'other'):
        if k not in kinds:
            raise SystemExit(f'dispatch mode walk: the configuration needs a fallback of kind {k}')
    n = len(tok.table)
    pmod = lambda fn: 'P' + fn[0].upper() + fn[1:]
    layout = '\n'.join(d.get('layout_doc', ['The storage layout is in docs/MAP.md.']))
    rep = {
        '@MOD@': tok.mod, '@ROOT@': tok.root, '@DIR@': tok.dir, '@TOKEN@': tok.name,
        '@ADDRESS@': tok.cfg.get('address', '?'), '@LAYOUT@': layout, '@N@': str(n),
        # `dispatch.split_doc`: the sentence of the head of Map.lean on why the table is split
        # (the default is for code compiled with the optimizer)
        '@SPLIT@': d.get('split_doc', 'The code was compiled with the optimizer, so the table\n'
                         'is split by GT comparisons and is not walked entry by entry.'),
        '@ENTRIES@': ',\n'.join(f'  (0x{k:08x}, {dst})' for k, dst in tok.table),
        '@PVALUE@': pmod(kinds['value']), '@PSHORT@': pmod(kinds['short']),
        '@POTHER@': pmod(kinds['other']), '@VALUE@': kinds['value'], '@SHORT@': kinds['short'],
        '@OTHER@': kinds['other'],
    }
    files = {'Code.lean': CODE, 'Steps.lean': STEPS, 'Map.lean': WMAP,
             os.path.join('Complete', 'Dispatch.lean'): WCOMPLETE}
    for rel, text in files.items():
        for k, v in rep.items():
            text = text.replace(k, v)
        if '@' in text.replace('@[irreducible]', ''):
            raise SystemExit(f'{rel}: a placeholder is left')
        path = os.path.join(tok.lean_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write(text)
    print(f'dispatcher files (mode walk): {n} entries')


def main():
    tok = tokenlib.load()
    d = tok.cfg['dispatch']
    if not d.get('generate'):
        print('dispatcher files: hand-written for this token (dispatch.generate is not set)')
        return
    if d.get('mode') == 'walk':
        return walk_mode(tok, d)
    s = shape(tok)
    if tok.prelude_gas != 62 or tok.entry_gas != 22:
        raise SystemExit('dispatch.prelude_gas and entry_gas must be 62 and 22 for this shape')
    if tok.memory_words != [0, 0, s['fp']]:
        raise SystemExit(f'dispatch.memory_words must be [0, 0, {s["fp"]}]')
    n = s['n']
    layout = '\n'.join(d.get('layout_doc', ['The storage layout is in docs/MAP.md.']))
    rep = {
        '@MOD@': tok.mod, '@ROOT@': tok.root, '@DIR@': tok.dir, '@TOKEN@': tok.name,
        '@ADDRESS@': tok.cfg.get('address', '?'), '@LAYOUT@': layout,
        '@FPH@': f'{s["fp"]:02x}', '@FP@': str(s['fp']),
        '@FBH@': f'{s["fb"] >> 8:02x} {s["fb"] & 255:02x}', '@FBH4@': f'{s["fb"]:04x}',
        '@FB@': str(s['fb']), '@FBM1@': str(s['fb'] - 1), '@START@': str(s['start']),
        '@N@': str(n), '@VG@': str(s['value_gas']), '@VG62@': str(62 + s['value_gas']),
        '@UNK@': str(62 + 22 * n + 7),
        '@ENTRIES@': ',\n'.join(f'  (0x{k:08x}, {dst})' for k, dst in tok.table),
        '@RFLS@': ' | '.join(['rfl'] * n),
        '@DUPTXT@': 'DUP1 ' if s['dup'] else '',
        '@DUPSTEP@': '    step dupR 0\n' if s['dup'] else '',
    }
    files = {'Code.lean': CODE, 'Steps.lean': STEPS, 'Map.lean': MAP, 'Enter.lean': ENTER,
             os.path.join('Spec', 'Dispatch.lean'): SPEC,
             os.path.join('Complete', 'Dispatch.lean'): COMPLETE}
    for rel, text in files.items():
        for k, v in rep.items():
            text = text.replace(k, v)
        if '@' in text.replace('@[irreducible]', ''):
            raise SystemExit(f'{rel}: a placeholder is left')
        path = os.path.join(tok.lean_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write(text)
    print(f'dispatcher files: {n} entries, fallback at {s["fb"]}, free pointer 0x{s["fp"]:02x}, '
          f'value revert {s["value_gas"]} gas')


main()
