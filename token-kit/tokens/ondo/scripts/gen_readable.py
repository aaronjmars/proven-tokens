def facts_unopt08(conds):
    """`readable_opts.facts = "unopt08"`: the facts of the conditions of Solidity 0.8 code
    compiled with the optimizer off. The size check of the decoder is
    `ISZERO (SLT ((4 + (CALLDATASIZE - 4)) - 4) k)`, a checked addition is
    `ISZERO (GT a (MAX - v))`, a checked subtraction or a `require(a >= v)` is `ISZERO (LT a v)`,
    a `require(v <= a)` is `ISZERO (GT v a)`. A condition that is a masked word is its own
    fact."""
    out = []
    for (cn, c, taken) in conds:
        i = cn[2:]
        if c.startswith(SIZEU) and taken:
            k = int(re.search(r'\((\d+) : U256\)\)\)$', c).group(1))
            out.append(f'have z{i} : 4 + {k} ≤ message.data.size := '
                       f"size_of_slt_u hsize hsize' (by decide) {cn}")
        elif c.startswith('(equal '):
            out.append(f'have e{i} := Readable.{"eq" if taken else "ne"}_of_equal {cn}')
        elif c.startswith('(isZero (equal '):
            out.append(f'have e{i} := Readable.{"ne" if taken else "eq"}_of_isZero_equal {cn}')
        elif c.startswith('(isZero (greaterThan ') and MAXSUB in c and taken:
            out.append(f'have b{i} := add_bound_submax {cn}')
            out.append(f'have f{i} := add_nat_submax {cn}')
        elif c.startswith('(isZero (greaterThan ') and taken:
            out.append(f'have l{i} := Supply.le_of_cond_gt1 {cn}')
        elif c.startswith('(isZero (lessThan ') and taken:
            out.append(f'have l{i} := Supply.le_of_cond_lt1 {cn}')
            out.append(f'have f{i} := Supply.sub_nat_lt1 {cn}')
        elif c.startswith('(isZero ') and taken:
            out.append(f'have v{i} := Readable.value_of_cond {cn}')
        elif c.startswith('(bitwiseAnd '):
            pass
        else:
            raise SystemExit('gen_readable (unopt08): no fact for the shape of %s %s' % (cn, c[:80]))
    return out


def facts06(conds, require_lt=False):
    """`readable_opts.facts = "checked06"`: the facts of the conditions of Solidity 0.5 and 0.6
    code compiled with the optimizer on, in the style of DAI (lemmas of Evm/Opt06.lean,
    Evm/Readable.lean and Evm/ReadableOpt.lean). An equation or its negation is given in both
    directions (`e<i>` and `e<i>'`). `readable_opts.require_lt` (`require_lt`): a taken
    `ISZERO (LT x a)` is `require(x >= a)` of code compiled with the optimizer off, and gives the
    two facts of the SafeMath sub of `a` from `x` (Evm/Unopt05.lean)."""
    out = []
    for (cn, c, taken) in conds:
        i = cn[2:]
        if c.startswith('(isZero (lessThan (sub (BitVec.ofNat 256 message.data.size) (4 : U256)) ('):
            if taken:
                k = int(re.search(r'\((\d+) : U256\)\)\)$', c).group(1))
                out.append(f'have z{i} : 4 + {k} ≤ message.data.size := '
                           f"Readable.size_of_cond hsize hsize' {cn}")
        elif c.startswith('(equal '):
            out.append(f'have e{i} := Readable.{"eq" if taken else "ne"}_of_equal {cn}')
            out.append(f"have e{i}' := e{i}.symm")
        elif c.startswith('(isZero (isZero (equal '):
            out.append(f'have e{i} := Readable.{"eq" if taken else "ne"}_of_cond2 {cn}')
            out.append(f"have e{i}' := e{i}.symm")
        elif c.startswith('(isZero (equal '):
            out.append(f'have e{i} := Readable.{"ne" if taken else "eq"}_of_isZero_equal {cn}')
            out.append(f"have e{i}' := e{i}.symm")
        elif c.startswith('(isZero (greaterThan (sub ') and taken:
            out.append(f'have l{i} := le_of_sub_check {cn}')
            out.append(f'have f{i} := sub_nat_check {cn}')
        elif c.startswith('(isZero (greaterThan '):
            if taken:
                out.append(f'have l{i} := Readable.le_of_cond_gt1 {cn}')
                out.append(f'have f{i} := Readable.sub_fact1 {cn}')
            else:
                out.append(f'have g{i} := Readable.lt_of_cond_gt1 {cn}')
        elif c.startswith('(isZero (lessThan (add ') and taken:
            out.append(f'have b{i} := add_bound_check {cn}')
            out.append(f'have f{i} := add_nat_check {cn}')
        elif require_lt and c.startswith('(isZero (lessThan ') and taken:
            # `require(x >= a)` with the optimizer off; the check of the SafeMath sub that
            # follows it is a dead branch (paths.dead_rules sub_after_ge_lt), so its two facts
            # come from the require
            out.append(f'have l{i} := le_of_sub_check (sub_check_of_ge_lt {cn})')
            out.append(f'have f{i} := sub_nat_check (sub_check_of_ge_lt {cn})')
        elif c.startswith('(isZero (isZero '):
            out.append(f'have n{i} := Readable.{"ne_of_cond2z" if taken else "zero_of_cond2z"} {cn}')
        elif c.startswith('(isZero '):
            out.append(f'have v{i} := Readable.{"value_of_cond" if taken else "ne_of_isZero0"} {cn}')
        elif taken is not None and not c.startswith('('):
            # a word as its own condition
            out.append(f'have w{i} := {cn}')
        else:
            print('  no fact for the shape of', cn, c[:60], file=sys.stderr)
    return out


def main():
    tok = tokenlib.load()
    d = json.load(open(tok.paths_json))
    descs = tok.cfg['readable']
    ev = []
    for name, sig in tok.cfg.get('events', {}).items():
        t = int.from_bytes(keccak256(sig.encode()), 'big')
        ev.append(f'/-- The topic of the event `{sig}`. -/\nabbrev {name} : U256 := ({t} : U256)\n')
    has_tot = 'totalSupply' in tok.slots
    opts = tok.cfg.get('readable_opts', {})
    ENDS = 'EndsL runChild' if tok.logic else 'Ends fork'
    close = opts.get('close', 'readable_close')
    mkfacts = {'checked08': facts08, 'checked06': facts06,
               'unopt08': facts_unopt08}.get(opts.get('facts'), facts)
    if opts.get('facts') == 'checked06' and opts.get('require_lt'):
        mkfacts = lambda conds: facts06(conds, require_lt=True)
    if opts.get('facts') == 'checked08' and (opts.get('symm') or opts.get('add_gt')
                                             or opts.get('add_gtc')):
        mkfacts = lambda conds: facts08(conds, symm=bool(opts.get('symm')),
                                        add_gt=bool(opts.get('add_gt')),
                                        add_gtc=bool(opts.get('add_gtc')))
    raw_caller = opts.get('caller_key') == 'raw'
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, TOKEN=tok.name, MASK=MASK,
                     genby=opts.get('generated_by', 'scripts/gen_readable.py'),
                     imports=''.join('\nimport ' + x for x in opts.get('imports', [])),
                     vars='variable {bound : Nat} {runChild : MessageRunner fork Nat bound}\n'
                     if tok.logic else '',
                     header=''.join('\n' + x.replace('MASK', MASK) + '\n'
                                    for x in opts.get('header', [])),
                     bal=tok.slots['balances'], allow=tok.slots['allowances'],
                     totblock=TOTBLOCK.format(tot=tok.slots['totalSupply']) if has_tot else '',
                     events='\n'.join(ev))]
    abbrevs = [a for a in ABBREVS if has_tot or a != 'totalSupply']
    unfold = ', '.join(abbrevs + opts.get('unfold', []) + list(tok.cfg.get('events', {})))
    slots_all = SLOTS if has_tot else SLOTS_NOTOT
    extra = ''.join(', ' + x for x in tok.cfg.get('readable_simp', []) + opts.get('simp', []))
    dispatch = tok.cfg['dispatch'].get(
        'size_proof', "obtain ⟨hsize, -, -⟩ := ends_ok_dispatch hfork hsize' start hrun hok")
    n_thm = 0
    items = []
    for f in tok.funcs:
        if tok.explicit_size:
            items.append((f['name'], "    (hsize : 4 ≤ message.data.size)\n"
                          "    (hsize' : message.data.size < 2 ^ 256)\n"
                          f"    (hsel : selector message.data = 0x{f['selector']:08x})\n",
                          "hfork hsize hsize' hsel"))
        else:
            items.append((f['name'], "    (hsize' : message.data.size < 2 ^ 256)\n"
                          f"    (hsel : selector message.data = 0x{f['selector']:08x})\n",
                          "hfork hsize' hsel"))
    for f in tok.fallbacks:
        if f['kind'] == 'short':
            items.append((f['name'], "    (hsize : message.data.size < 4)\n", "hfork hsize"))
        else:
            items.append((f['name'], "    (hsize : 4 ≤ message.data.size)\n"
                          "    (hsize' : message.data.size < 2 ^ 256)\n"
                          "    (hsel : BitVec.ofNat 256 (selector message.data) ∉ "
                          "ENTRIES.map Prod.fst)\n", "hfork hsize hsize' hsel"))
    for fn, hyps, args in items:
        if fn not in descs:
            print('no readable description for', fn, file=sys.stderr)
            continue
        ds = descs[fn]
        ps = [p for p in d[fn]['paths'] if p['kind'] == 'ok']
        lets = {k: f'({v})' for k, v in ds.get('let', {}).items()}
        fill = lambda t: re.sub(r'\{(\w+)\}', lambda m: lets[m.group(1)], t)
        req = [fill(c) for c in ds['requires']]
        ens = [fill(c) for c in ds['ensures']]
        cases = [fill(c) for c in ds.get('cases', [])]
        sep = ds.get('sep', ps[0]['wrote'])
        if opts.get('heartbeats') and len(ps) > 1:
            # `readable_opts.heartbeats`: the budget of a function with several success paths
            o.append('set_option maxHeartbeats %d in\n' % opts['heartbeats'])
        o.append(f'/-- {ds["doc"]} -/\n')
        o.append(f'theorem {fn}_readable (hfork : .berlin ≤ fork)\n' + hyps
                 + ('    (hsep : Sep (callKeys message))\n' if sep else '') +
                 '    {gas : Nat} {evm s : Evm fork Nat}\n'
                 '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                 '    (hrun : ' + ENDS + ' evm s) (hok : s.error = none) :\n')
        o.append('    (' + ' ∧\n      '.join(f'({c})' for c in req) + ') ∧\n')
        o.append('    (' + ' ∧\n      '.join(f'({c})' for c in ens) + ') := by\n')
        slots = (slots_all if sep else '') + extra
        many = len(ps) > 1
        # several success paths: each path closes the cases it excludes (default), or the same
        # claims are proved on each path as they are (`same_claims`)
        same = many and opts.get('several_paths') == 'same_claims'

        def block(p, first):
            """The proof for one success path; `first`: the lines that bring its facts."""
            hc = [c[0] for c in p['conds']]
            L = list(first)
            if not tok.explicit_size and not same:
                L.append(dispatch)
            L.append('clear hgas hg' + ('' if many and not same else ' start hrun hok'))
            L.append(f'try simp only [{unfold}]')
            L.append('rw [hst, hout, hsub]')
            L.append('clear hst hout hsub')
            for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                     '(loadWord message.data 36 32)']):
                if raw_caller and i == 0:
                    # `readable_opts.caller_key = "raw"`: the caller is a key with no mask
                    L.append(f'have hm1 : {key} ∈ callKeys message := by simp [callKeys]')
                    continue
                L.append(f'have hm{i + 1} : bitwiseAnd {MASK} {key} ∈ callKeys message := by '
                         'simp [callKeys]')
            simp0 = SIMP.format(slots=slots, cases='')
            if hc:
                L.append(f'try simp (disch := slot_side) only {simp0} at {" ".join(hc)}')

            def leaf(ind, chyps):
                pad = '  ' * ind
                out = []
                simp1 = SIMP.format(slots=slots, cases=''.join(', ' + h for h in chyps))
                if len(cases) > 1:
                    # each case equation in the words that the other equations leave
                    pos = [h for h in chyps if h + "'" not in chyps and not h.endswith("'")]
                    for h in [h for h in chyps if not h.endswith("'")]:
                        oth = [x for x in pos if x != h]
                        tgt = h + (f" {h}'" if h + "'" in chyps else '')
                        if oth:
                            out.append(f'{pad}try simp only [{", ".join(oth)}] at {tgt}')
                if chyps and hc:
                    out.append(f'{pad}try simp (disch := slot_side) only {simp1} at {" ".join(hc)}')
                out += [pad + x for x in mkfacts(p['conds'])]
                if many and hc and not same:
                    out.append(f'{pad}clear {" ".join(hc)}')
                rq = '?_' if len(req) == 1 else '⟨' + ', '.join(['?_'] * len(req)) + '⟩'
                if many and not same:
                    # a case that this path excludes
                    out.append(f'{pad}first')
                    out.append(f'{pad}| (exfalso; first | (with_reducible contradiction) | omega)')
                    out.append(f'{pad}| skip')
                    out.append(f'{pad}all_goals refine ⟨' + rq + ', '
                               + ', '.join(['?_'] * len(ens)) + '⟩')
                else:
                    out.append(pad + 'refine ⟨' + rq + ', ' + ', '.join(['?_'] * len(ens)) + '⟩')
                out.append(f'{pad}all_goals first')
                out.append(f'{pad}  | (simp (disch := slot_side) only {simp1}; done)')
                out.append(f'{pad}  | ((try simp (disch := slot_side) only {simp1}); {close})')
                return out

            def split(ind, todo, chyps, k=1):
                pad = '  ' * ind
                if not todo:
                    return leaf(ind, chyps)
                c = todo[0]
                lhs, rhs = [x.strip() for x in c.split(' = ')]
                out = [f'{pad}by_cases hd{k} : {c}']
                # the equation rewrites the left word to the right one
                out.append(f'{pad}· simp only [{unfold}] at hd{k}')
                out += split(ind + 1, todo[1:], chyps + [f'hd{k}'], k + 1)
                out.append(f'{pad}· have hd{k}\' : ¬({rhs} = {lhs}) := fun e => hd{k} e.symm')
                out.append(f'{pad}  simp only [{unfold}] at hd{k} hd{k}\'')
                out += split(ind + 1, todo[1:], chyps + [f'hd{k}', f'hd{k}\''], k + 1)
                return out

            return '\n'.join('  ' + x for x in L) + '\n' + '\n'.join(split(1, cases, [])) + '\n'

        def pattern(p):
            return [c[0] for c in p['conds']] + (['hstatic', 'hacc'] if p['wrote'] else []) + \
                ['hgas', 'hout', 'hg', 'hst', 'hsub']

        if not many:
            p = ps[0]
            o.append(block(p, [f"obtain ⟨{', '.join(pattern(p))}⟩ :=\n    ok_{fn} {args} start hrun hok"]))
            o.append('\n')
        elif same:
            if not tok.explicit_size:
                o.append(f'  {dispatch}\n')
            o.append(f"  rcases ok_{fn} {args} start hrun hok with\n    "
                     + ' | '.join(f'⟨{", ".join(pattern(q))}⟩' for q in ps) + '\n')
            for q in ps:
                lines = [x[2:] for x in block(q, []).splitlines()]
                o.append('  · ' + '\n    '.join(lines) + '\n')
            o.append('\n')
        else:
            o.append(f'  have hall := ok_{fn} {args} start hrun hok\n')
            o.append('  clear start hrun hok\n')
            o.append('  rcases hall with %s\n' % ' | '.join(['hall'] * len(ps)))
            for p in ps:
                b = block(p, [f"obtain ⟨{', '.join(pattern(p))}⟩ := hall"])
                lines = b.splitlines()
                o.append('  · ' + lines[0][2:] + '\n')
                o.append(''.join('  ' + x + '\n' for x in lines[1:]))
            o.append('\n')
        n_thm += 1
    o.append(f'end {tok.root}.Readable\n')
    open(os.path.join(tok.lean_dir, 'Readable.lean'), 'w').write(''.join(o))
    print('Readable.lean:', n_thm, 'theorems')


