def facts(conds):
    """One line per condition of the success path: the fact its shape gives."""
    out, names = [], []
    for (cn, c, taken) in conds:
        i = cn[2:]
        if c.startswith('(isZero (isZero (equal '):
            # `a == b` as a jump condition, on either branch
            out.append(f'have e{i} := Readable.{"eq" if taken else "ne"}_of_cond2 {cn}')
            continue
        if not taken:
            if c.startswith('(isZero (greaterThan '):
                out.append(f'have g{i} := Readable.lt_of_cond_gt1 {cn}')
            continue
        if c == '(isZero message.value)':
            out.append(f'have v{i} := Readable.value_of_cond {cn}')
        elif c.startswith('(isZero (lessThan (sub (BitVec.ofNat 256 message.data.size) (4 : U256)) ('):
            k = int(re.search(r'\((\d+) : U256\)\)\)$', c).group(1))
            out.append(f'have z{i} : 4 + {k} ≤ message.data.size := '
                       f"Readable.size_of_cond hsize hsize' {cn}")
        elif c.startswith('(isZero (isZero (isZero (equal ') and c.endswith('(0 : U256)))))'):
            out.append(f'have n{i} := Readable.ne_of_cond {cn}')
        elif c.startswith('(isZero (isZero (isZero (greaterThan '):
            out.append(f'have l{i} := Supply.le_of_cond_gt {cn}')
            out.append(f'have f{i} := Supply.sub_fact {cn}')
        elif c.startswith('(isZero (isZero (isZero (lessThan (add '):
            out.append(f'have b{i} := Readable.add_bound {cn}')
            out.append(f'have f{i} := Supply.add_fact {cn}')
        elif c.startswith('(isZero (isZero (isZero (lessThan '):
            # `require(a >= v)` as solc 0.4 compiles it
            out.append(f'have l{i} := Supply.le_of_cond_lt {cn}')
            out.append(f'have f{i} := Supply.sub_fact_lt {cn}')
        elif c.startswith('(isZero (greaterThan '):
            out.append(f'have l{i} := Readable.le_of_cond_gt1 {cn}')
            out.append(f'have f{i} := Readable.sub_fact1 {cn}')
        else:
            print('  no fact for the shape of', cn, c[:60], file=sys.stderr)
    return out


def facts08(conds, symm=False, add_gt=False, add_gtc=False):
    """`readable_opts.facts = "checked08"`: the facts of the conditions of optimized Solidity
    0.8 code (lemmas of Evm/ReadableOpt.lean and Evm/SupplyOpt.lean). A condition that is a
    masked word (`AND x mask`) is its own fact.

    `readable_opts.symm = true` (`symm`): an equation or its negation is given in both
    directions (`e<i>` and `e<i>'`). `readable_opts.add_gt = true` (`add_gt`): a taken
    `ISZERO (GT a (ADD v a))` is the check of the addition `v + a` (SKY; lemmas of
    Evm/SupplyUnchecked.lean)."""
    out = []
    for (cn, c, taken) in conds:
        i = cn[2:]
        if c.startswith('(isZero (signedLessThan (sub (BitVec.ofNat 256 message.data.size) (4 : U256)) ('):
            k = int(re.search(r'\((\d+) : U256\)\)\)$', c).group(1))
            out.append(f'have z{i} : 4 + {k} ≤ message.data.size := '
                       f"Readable.size_of_slt hsize hsize' (by decide) {cn}")
        elif c.startswith('(equal '):
            out.append(f'have e{i} := Readable.{"eq" if taken else "ne"}_of_equal {cn}')
            if symm:
                out.append(f"have e{i}' := e{i}.symm")
        elif c.startswith('(isZero (equal '):
            out.append(f'have e{i} := Readable.{"ne" if taken else "eq"}_of_isZero_equal {cn}')
            if symm:
                out.append(f"have e{i}' := e{i}.symm")
        elif c.startswith('(isZero (isZero (greaterThan ') and not taken:
            out.append(f'have l{i} := Readable.le_of_cond2_gt {cn}')
        elif add_gt and c.startswith('(isZero (greaterThan ') and '(bitwiseNot ' not in c and taken:
            out.append(f'have b{i} := Supply.add_bound_gt {cn}')
            out.append(f'have f{i} := Supply.add_nat_gt {cn}')
        elif c.startswith('(isZero (greaterThan ') and '(bitwiseNot ' in c and taken:
            out.append(f'have b{i} := Supply.add_bound_not {cn}')
            out.append(f'have f{i} := Supply.add_nat_not {cn}')
        elif add_gtc and c.startswith('(isZero (greaterThan ') and '(add ' in c and taken:
            # `readable_opts.add_gtc` (USDE, ENA): the checked addition of solc 0.8.19 with the
            # optimizer on, ISZERO (GT a (ADD v a)) (lemmas Supply.add_bound_gtc / add_nat_gtc)
            out.append(f'have b{i} := Supply.add_bound_gtc {cn}')
            out.append(f'have f{i} := Supply.add_nat_gtc {cn}')
        elif c.startswith('(isZero (lessThan ') and taken:
            out.append(f'have l{i} := Supply.le_of_cond_lt1 {cn}')
            out.append(f'have f{i} := Supply.sub_nat_lt1 {cn}')
        elif c.startswith('(isZero (isZero '):
            out.append(f'have n{i} := Readable.{"ne_of_cond2z" if taken else "zero_of_cond2z"} {cn}')
        elif c.startswith('(isZero '):
            out.append(f'have v{i} := Readable.{"value_of_cond" if taken else "ne_of_isZero0"} {cn}')
        elif c.startswith('(bitwiseAnd '):
            pass
        else:
            print('  no fact for the shape of', cn, c[:60], file=sys.stderr)
    return out


