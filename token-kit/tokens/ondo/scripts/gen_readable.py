#!/usr/bin/env python3
"""Write <Root>/<Dir>/Readable.lean: one readable corollary `<fn>_readable` per function, from
the small description of the function in the configuration (`readable.<fn>`) and the success
path in paths.json.

A description has:
- `let`: names for the words of the call, e.g. {"from": "sender message"}; a claim writes
  `{from}`;
- `requires`: what a successful call implies about the call and the START state;
- `ensures`: the output, the END storage in terms of the start storage, and the logs;
- `cases` (optional): equations between two address words on which the proof splits (the case
  `from = to` of a transfer);
- `sep` (optional, default true for a function that writes): whether the corollary takes the
  hypothesis on keccak `Sep (callKeys message)`.

A function with several success paths gets one corollary. By default each path proves the claims
it can reach and closes the cases it excludes; with `readable_opts.several_paths = "same_claims"`
the same claims are proved on each path with no such step. `readable_opts.simp` and
`readable_simp` (both optional) list more rewrite rules for the proofs of a token.

The claims are Lean propositions over `message`, `state`, `substate` (the start) and `s` (the
frame where the run ends), with the abbreviations of the header below (`balance`, `allowance`,
`totalSupply`, `sender`, `addrArg1`, `addrArg2`, `arg1`..`arg3`, the event topics).

The proof is the same for every function: take the raw conditions and results from `ok_<fn>`,
turn each condition into a fact by its shape, rewrite the reads of written slots with the slot
rules of Sep.lean, split on the cases, and close each claim with `readable_close`.

Usage: gen_readable.py <config/token.json>"""
