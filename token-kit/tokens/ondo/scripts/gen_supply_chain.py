#!/usr/bin/env python3
"""The supply invariant for a token whose functions are composed of chained segments
(`paths.auto_chain` of gen_paths.py; UNI: the code that moves the votes of two delegates).
Called by gen_supply.py with `"supply": {"style": "chain", ...}`. It writes two files:

ONDO copy: the segments are of two kinds (`supply.seg_kinds`, by label). A `frame` segment
(the code that moves votes) gets `<seg>_frame` as before, but for the checkpoint slots of a
list `D` of delegates: the binders of the segment that are keys of checkpoint slots (found from
the terms of its paths) must be in `D`. A `delta` segment (the transfer code: it writes
balances, or leads to the code that does) gets `<seg>_delta`: the run keeps the difference `D`,
if the binders that are keys of balances are in the list `A` of `Sep` and their delegates in
the state at the start of the segment are in `D`. Both lists are finite; `Sep` has no field
over every address word.

- <Dir>/Frame.lean: for each chained segment `<seg>`, the theorem `<seg>_frame`: a run of the
  segment that ends with no error leaves every storage word of the contract as it was, but the
  slots of the predicate `supply.frame_pred` (UNI: `CkSlot`, the checkpoint slots). A path of a
  segment that ends in another segment uses the theorem of that one. No hypothesis on keccak.
- <Dir>/Invariant.lean: for each function, `delta_<fn>` (the sum of the balances minus the
  total supply is unchanged; a path that ends in a segment uses `<seg>_frame` and the lemma
  `supply.frame_lemma`), `supply_<fn>`, then `delta_step` and `supply_preserved`. A function
  with a path that stops at a call (a `prefix_functions` entry) becomes a hypothesis
  `selector message.data ≠ ...` of the last two.

Keys of `supply`: `frame_pred`, `frame_rules` (rewrite rules of a write that the predicate
excludes), `frame_lemma`, `D` (the name of the difference), `norm`, `rules`, `disch`, `what`,
`frame_imports`, `imports`; `arith` (numerals as natural numbers, in every hypothesis),
`arith_small` (conditional rules that drop a mask from a word known to be small) and
`arith_goal` (conditional rules that give a checked sum or difference as a natural number;
their conditions are the facts read from the checks of the path)."""
import json
import os
import re

M = '(1461501637330902918203684832716283019655932542975 : U256)'

FHEAD = """import {MOD}.Gen
{imports}

/-!
# What the chained segments of {TOKEN} leave unchanged

Generated by `scripts/gen_supply_chain.py` from the success paths of `scripts/gen_paths.py`; do
not edit. Lean checks every statement against `CODE`.

- `<seg>_frame`: if the run of the segment `<seg>` ends with no error (`<seg>_ends`, the
  conclusion of `ok_<seg>_ends`), then every storage word of the contract at a slot `k` that
  is not `{pred} k` is the same at the end as at the start of the segment.

No hypothesis on keccak is used: the statement is about the slots the segment writes.
-/

set_option autoImplicit false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false
set_option maxRecDepth 4096

namespace {ROOT}

open UsdtVerify
open TokenKit
open {ROOT}.Paths {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic

variable {{fork : Fork}} {{message : Message fork}}
variable {{state : State.TransactionState}} {{substate : Substate}}

"""

IHEAD = """import {MOD}.Gen
import {MOD}.Gen.Loops
import {MOD}.Sep
import {MOD}.Frame
{imports}

/-!
# The supply invariant of {TOKEN} is kept by every successful call

Generated by `scripts/gen_supply_chain.py` from the success paths of `scripts/gen_paths.py`; do
not edit. Lean checks every statement against `CODE`.

`{D}` is the difference of the invariant ({what}); the invariant `Inv` is `{D} = 0`.

- `delta_<fn>`: a run of `CODE` from pc 0 with the selector of `<fn>` that ends with no error
  ends with the same `{D}` it started with, under `Sep (callKeys message)`. Nothing is assumed
  about the start state.
- `supply_<fn>`: so the run keeps `Inv`.
- `delta_step`, `supply_preserved`: the same for {scope}.

`Sep (callKeys message)` is the hypothesis on keccak of {ROOT}/{DIR}/Sep.lean; it is assumed,
not proved.
-/

set_option autoImplicit false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false
set_option maxRecDepth 4096

namespace {ROOT}

open UsdtVerify
open TokenKit
open {ROOT}.Paths {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic

variable {{fork : Fork}} {{message : Message fork}}
variable {{state : State.TransactionState}} {{substate : Substate}}
variable {{bound : Nat}} {{runChild : MessageRunner fork Nat bound}}

"""


def pattern(p):
    """The names of the conjuncts of the disjunct of the path `p` in `ok_<fn>` / `<seg>_ends`."""
    names = [c[0] for c in p['conds']] + (['hstat', 'hacc'] if p['wrote'] else [])
    if p['kind'] == 'ok':
        return names + ['hgas', 'hout', 'hg', 'hst', 'hsub']
    return names + ['hgas', 'hch']


def ends_binders(tok, seg):
    """The binders of `<seg>_ends` after `(s : Evm fork Nat)`, and their names."""
    path = os.path.join(tok.lean_dir, 'Gen', 'P%s%s.lean' % (seg[0].upper(), seg[1:]))
    text = open(path).read()
    m = re.search(r'def %s_ends \(fork : Fork\).*?\(s : Evm fork Nat\)(.*?) : Prop :=' % seg,
                  text, re.S)
    if not m:
        raise SystemExit('gen_supply_chain: no definition of %s_ends' % seg)
    tail = ' '.join(m.group(1).split())
    names = []
    for g in re.findall(r'[({]([^(){}]*?) : [^(){}]*[)}]', tail):
        names += g.split()
    return tail, names


MASK = M
KEYRE = re.compile(r'mapSlot \(bitwiseAnd (?:a(\d+) M|M a(\d+))\) \((\d+) : U256\)')


def keys_of(strings, slots):
    out = set()
    for s in strings:
        for m in KEYRE.finditer(s.replace(MASK, 'M')):
            if int(m.group(3)) in slots:
                out.add(int(m.group(1) or m.group(2)))
    return out


def binder_of(val):
    """The number of the binder `a<i>` that the value is (masked to 160 bits or not), or None."""
    m = re.fullmatch(r'a(\d+)|\(bitwiseAnd (?:a(\d+) M|M a(\d+))\)', val.replace(MASK, 'M'))
    return None if not m else int(m.group(1) or m.group(2) or m.group(3))


# proves that a key is in the list `A` or `D` (macros of Sep.lean): it is a hypothesis, or a
# hypothesis once the masks are in one form and the reads go through the writes of balances and
# allowances, or a member of the lists of the call. The hypotheses are compared without unfolding
# (`with_reducible`): a plain `assumption` on two different `mapSlot` terms runs out of heartbeats.
MEM = '(by key_mem)'
MEMS = '(by key_mem_sep hsep)'


def run(tok, d, sup):
    auto = tok.cfg.get('paths', {}).get('auto_chain', {})
    labels = set(auto.values())
    kinds = sup['seg_kinds']
    kind_of = lambda nm: kinds[re.sub(r'\d+$', '', nm)]
    segs = [k for k, v in d.items() if isinstance(v, dict) and re.sub(r'\d+$', '', k) in labels
            and re.search(r'\d+$', k)]
    good = lambda p: p['kind'] == 'ok' or (p['kind'] == 'at' and p.get('chain'))
    live = lambda nm: [p for p in d[nm]['paths'] if p['kind'] in ('ok', 'at')]
    order, seen = [], set()

    def visit(nm):
        if nm in seen:
            return
        seen.add(nm)
        for p in live(nm):
            if p.get('chain'):
                visit(p['chain']['seg'])
        order.append(nm)
    for nm in segs:
        visit(nm)
    pred, D = sup['frame_pred'], sup.get('D', 'Dsum')
    disch = sup.get('disch', 'slot_side')
    # the binders of a segment that are keys: of checkpoint slots (CK), of balances (BAL)
    CK, BAL = {}, {}
    for seg in order:
        ps = live(seg)
        if not all(good(p) for p in ps):
            raise SystemExit('gen_supply_chain: %s has a path that stops at a call' % seg)
        strs = []
        for p in ps:
            strs += [p['state']] + [c[1] for c in p['conds']]
            if p.get('chain'):
                strs += list(p['chain']['vals'].values())
        ck = keys_of(strs, (8, 9)) if kind_of(seg) == 'frame' else set()
        bal = keys_of(strs, (2, 6, 7)) if kind_of(seg) == 'delta' else set()
        for p in ps:
            if not p.get('chain'):
                continue
            sub, vals = p['chain']['seg'], p['chain']['vals']
            if kind_of(seg) == 'frame':
                for j in CK[sub]:
                    b = binder_of(vals['a%d' % j])
                    if b is None:
                        raise SystemExit('gen_supply_chain: %s passes to %s a delegate that is no '
                                         'binder: %s' % (seg, sub, vals['a%d' % j][:200]))
                    ck.add(b)
            elif kind_of(sub) == 'delta':
                for j in BAL[sub]:
                    b = binder_of(vals['a%d' % j])
                    if b is None:
                        raise SystemExit('gen_supply_chain: %s passes to %s a key that is no '
                                         'binder: %s' % (seg, sub, vals['a%d' % j][:200]))
                    bal.add(b)
        CK[seg], BAL[seg] = sorted(ck), sorted(bal)

    def sub_args(p, sep=True):
        """The proofs of the key hypotheses of the segment the path ends in."""
        sub = p['chain']['seg']
        m = MEMS if sep else MEM
        if kind_of(sub) == 'frame':
            return ''.join(' ' + m for _ in CK[sub])
        return ''.join(' ' + m for _ in BAL[sub]) + ''.join(' ' + m for _ in BAL[sub])

    def finish(p, top):
        """The tactic lines that prove `D C <state of p> = D C state` once the goal has it."""
        L = []
        cl = [x for x in pattern(p) if x[:2] != 'hc' or x == 'hch' if x not in ('hacc', 'hstat')]
        L.append('clear %s%s' % (' '.join(cl), ' start hrun hok' if top else ''))
        L.append('try simp only [%s] at *' % sup['norm'])
        if top:
            for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                     '(loadWord message.data 36 32)']):
                if i == 0:
                    L.append('have hm1 : %s ∈ callKeys message := by simp [callKeys]' % key)
                else:
                    L.append('have hm%d : bitwiseAnd %s %s ∈ callKeys message := by simp [callKeys]'
                             % (i + 1, M, key))
        hcs = ' '.join(c[0] for c in p['conds'])
        L += ['simp (disch := %s) only' % disch,
              '  [%s]' % sup['rules'],
              'first',
              '  | done',
              '  | (try generalize %s _ _ = d at *' % sup['D'],
              '     word_omega %s)' % hcs]
        return L

    o = [FHEAD.format(MOD=tok.mod, ROOT=tok.root, TOKEN=tok.name, pred=pred,
                      imports='\n'.join('import ' + m for m in sup.get('frame_imports', [])))]
    o.append('variable {A D : List U256} {R : U256}\n\n')
    for seg in order:
        ps = live(seg)
        tail, names = ends_binders(tok, seg)
        imp = re.sub(r'\(([^()]*)\)', r'{\1}', tail)
        ends = ('    (h : %s_ends fork message state substate gas s%s)\n'
                % (seg, ''.join(' ' + n for n in names if n != 'bound')))
        pats = ['⟨' + ', '.join(pattern(p)) + '⟩' for p in ps]
        if kind_of(seg) == 'frame':
            o.append('/-- A run of the segment `%s` that ends with no error changes no storage word '
                     'of the contract\nbut at the checkpoint slots of the delegates of `D`. -/\n' % seg)
            o.append('theorem %s_frame {gas : Nat} {s : Evm fork Nat}%s\n' % (seg, ' ' + imp if imp else ''))
            o.append(ends)
            for i in CK[seg]:
                o.append('    (hk%d : bitwiseAnd %s a%d ∈ D)\n' % (i, M, i))
            o.append('    (k : U256) (hk : ¬ %s D k) :\n' % pred)
            o.append('    storageAt s.state message.currentTarget k = '
                     'storageAt state message.currentTarget k := by\n')
            o.append('  unfold %s_ends at h\n' % seg)
            o.append('  rcases h with\n    %s\n' % ' |\n    '.join(pats))
            for p in ps:
                if p['kind'] == 'ok':
                    L = ['rw [hst]']
                else:
                    L = ['rw [%s_frame hch%s k hk]' % (p['chain']['seg'], sub_args(p, False))]
                if p['state'] != 'state':
                    L.append('clear %s' % ' '.join(x for x in pattern(p) if x not in ('hacc', 'hstat')))
                    L += ['simp (disch := %s) only' % disch, '  [%s]' % sup['frame_rules']]
                o.append('  · ' + '\n    '.join(L) + '\n')
            o.append('\n')
            continue
        o.append('/-- A run of the segment `%s` that ends with no error keeps the sum of the '
                 'balances minus\nthe total supply, when its address words are in `A` and their '
                 'delegates at the start of the\nsegment are in `D`. `hsep` is the hypothesis on '
                 'keccak (not proved). -/\n' % seg)
        o.append('theorem %s_delta (hsep : Sep A D R) {gas : Nat} {s : Evm fork Nat}%s\n'
                 % (seg, ' ' + imp if imp else ''))
        o.append(ends)
        for i in BAL[seg]:
            o.append('    (hb%d : bitwiseAnd %s a%d ∈ A)\n' % (i, M, i))
        for i in BAL[seg]:
            o.append('    (hd%d : delegOf message.currentTarget state (bitwiseAnd %s a%d) ∈ D)\n' % (i, M, i))
        o.append('    :\n    %s message.currentTarget s.state = %s message.currentTarget state := by\n' % (D, D))
        o.append('  unfold %s_ends at h\n' % seg)
        if BAL[seg]:
            o.append('  unfold delegOf at %s\n' % ' '.join('hd%d' % i for i in BAL[seg]))
        o.append('  rcases h with\n    %s\n' % ' |\n    '.join(pats))
        for p in ps:
            if p['kind'] == 'ok':
                L = ['rw [hst]']
            elif kind_of(p['chain']['seg']) == 'frame':
                L = ['rw [%s hsep (%s_frame hch%s)]' % (sup['frame_lemma'], p['chain']['seg'], sub_args(p))]
            else:
                L = ['rw [%s_delta hsep hch%s]' % (p['chain']['seg'], sub_args(p))]
            if p['state'] != 'state':
                L += finish(p, False)
            o.append('  · ' + '\n    '.join(L) + '\n')
        o.append('\n')
    o.append('end %s\n' % tok.root)
    open(os.path.join(tok.lean_dir, 'Frame.lean'), 'w').write(''.join(o))

    # ---- the functions
    loops = {f['index']: f for f in tok.loops}
    funcs = [f for f in tok.funcs if live(f['name']) and all(good(p) for p in live(f['name']))]
    by = {f['index']: f for f in funcs}
    nt = len(tok.table)
    skipped = [i for i in range(nt) if i not in by and i not in loops]
    scope = ('any selector' if not skipped else
             'any selector other than ' + ', '.join(f'0x{tok.table[i][0]:08x}' for i in skipped))
    Dt = lambda st: f'{D} message.currentTarget {st}'
    SEP = sup['sep']
    o = [IHEAD.format(MOD=tok.mod, ROOT=tok.root, DIR=tok.dir, TOKEN=tok.name, D=D, scope=scope,
                      what=sup.get('what', 'the sum of all balances minus the total supply'),
                      imports='\n'.join('import ' + m for m in sup.get('imports', []))
                      ).replace('Sep (callKeys message)', SEP)]

    def sig(kind, fn, sel, sep, inv):
        return ('theorem %s_%s (hfork : .berlin ≤ fork)\n' % (kind, fn) +
                '    (hsize\' : message.data.size < 2 ^ 256)\n' +
                '    (hsel : selector message.data = 0x%08x)\n' % sel +
                ('    (hsep : %s)\n' % SEP if sep else '') +
                ('    (hinv : Inv message.currentTarget state)\n' if inv else '') +
                '    {gas : Nat} {evm s : Evm fork Nat}\n'
                '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                '    (hrun : EndsL runChild evm s) (hok : s.error = none) :\n')

    def supply(fn, sel, sep):
        return ('/-- A successful call of `%s` keeps the invariant. -/\n' % fn +
                sig('supply', fn, sel, sep, True) +
                '    Inv message.currentTarget s.state := by\n'
                '  have h := delta_%s hfork hsize\' hsel %sstart hrun hok\n'
                '  unfold Inv %s at hinv ⊢\n'
                '  unfold %s at h\n'
                '  rw [h]\n'
                '  exact hinv\n\n' % (fn, 'hsep ' if sep else '', sup['inv_unfold'], D))

    for f in funcs:
        fn, sel = f['name'], f['selector']
        ps = live(fn)
        o.append('/-- A successful call of `%s` leaves `%s` as it was. -/\n' % (fn, D))
        o.append(sig('delta', fn, sel, True, False))
        o.append('    %s = %s := by\n' % (Dt('s.state'), Dt('state')))
        pats = ['⟨' + ', '.join(pattern(p)) + '⟩' for p in ps]
        o.append('  rcases ok_%s hfork hsize\' hsel start hrun hok with\n    %s\n'
                 % (fn, ' |\n    '.join(pats)))
        for p in ps:
            pre = []
            if p['kind'] == 'ok':
                L = ['rw [hst]']
            else:
                for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                         '(loadWord message.data 36 32)']):
                    if i == 0:
                        pre.append('have hm1 : %s ∈ callKeys message := by simp [callKeys]' % key)
                    else:
                        pre.append('have hm%d : bitwiseAnd %s %s ∈ callKeys message := by simp [callKeys]'
                                   % (i + 1, M, key))
                if kind_of(p['chain']['seg']) == 'frame':
                    L = pre + ['rw [%s hsep (%s_frame hch%s)]'
                               % (sup['frame_lemma'], p['chain']['seg'], sub_args(p))]
                else:
                    L = pre + ['rw [%s_delta hsep hch%s]' % (p['chain']['seg'], sub_args(p))]
            if p['state'] == 'state':
                o.append('  · ' + '\n    '.join(L) + '\n')
                continue
            if pre:
                L.append('clear hm1 hm2 hm3')
            L += finish(p, True)
            o.append('  · ' + '\n    '.join(L) + '\n')
        o.append('\n')
        o.append(supply(fn, sel, True))
    for f in loops.values():
        fn, sel = f['name'], f['selector']
        o.append('/-- A successful call of `%s` leaves `%s` as it was: it only reads. -/\n' % (fn, D))
        o.append(sig('delta', fn, sel, False, False))
        o.append('    %s = %s :=\n' % (Dt('s.state'), Dt('state')))
        o.append('  %s (Loops.ro_%s hfork hsize\' hsel start hrun hok)\n\n' % (sup['ro_lemma'], fn))
        o.append(supply(fn, sel, False))
    hs = ''.join('    (hsel%d : selector message.data ≠ 0x%08x)\n' % (i, tok.table[i][0])
                 for i in skipped)
    for kind, concl, doc in [
            ('delta', '%s = %s' % (Dt('s.state'), Dt('state')),
             'ends with the `%s` it started with.' % D),
            ('supply', 'Inv message.currentTarget s.state',
             'keeps the invariant.')]:
        name = 'delta_step' if kind == 'delta' else 'supply_preserved'
        o.append('/-- From Berlin, a run of `CODE` from pc 0 that ends with no error, with ' + scope
                 + ',\n' + doc + '\n`hsep` is the hypothesis on keccak (not proved). -/\n')
        o.append('theorem %s (hfork : .berlin ≤ fork)\n' % name +
                 '    (hsize\' : message.data.size < 2 ^ 256)\n' + hs +
                 '    (hsep : %s)\n' % SEP +
                 ('    (hinv : Inv message.currentTarget state)\n' if kind == 'supply' else '') +
                 '    {gas : Nat} {evm s : Evm fork Nat}\n'
                 '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                 '    (hrun : EndsL runChild evm s) (hok : s.error = none) :\n'
                 '    ' + concl + ' := by\n'
                 '  obtain ⟨_, _, i, hi⟩ := ends_ok_dispatch hfork hsize\' start hrun hok\n'
                 '  match i, hi with\n')
        inv = ' hinv' if kind == 'supply' else ''
        for i in range(nt):
            sel = tok.table[i][0]
            o.append('  | ⟨%d, _⟩, hi =>\n    have h : selector message.data = 0x%08x := hi\n' % (i, sel))
            if i in by:
                o.append('    exact %s_%s hfork hsize\' h hsep%s start hrun hok\n' % (kind, by[i]['name'], inv))
            elif i in loops:
                o.append('    exact %s_%s hfork hsize\' h%s start hrun hok\n' % (kind, loops[i]['name'], inv))
            else:
                o.append('    exact absurd h hsel%d\n' % i)
        o.append('  | ⟨n + %d, hn⟩, _ => exact absurd hn (by omega)\n\n' % nt)
    o.append('end %s\n' % tok.root)
    open(os.path.join(tok.lean_dir, 'Invariant.lean'), 'w').write(''.join(o))
    print('Frame.lean: %d segments; Invariant.lean: %d functions, %d read-only loops, %d left out'
          % (len(order), len(funcs), len(loops), len(skipped)))
