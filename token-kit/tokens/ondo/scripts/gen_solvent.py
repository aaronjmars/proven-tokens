#!/usr/bin/env python3
"""Write <Root>/<Dir>/Solvent.lean: for a token backed by the ether of its contract (config key
`backing` = "ether"), each function and fallback whose paths gen_paths.py followed to the end
keeps the solvency invariant `sum of balances <= ether of the contract`. A function of
`readonly_loops` takes its case from `ro_<fn>` of gen_loops.py. Functions that stop at an opcode
outside the simulated set (config key `stops`) are not here: they are proved by hand.

Usage: gen_solvent.py <config/token.json>"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402

M = '(1461501637330902918203684832716283019655932542975 : U256)'

HEAD = """import {MOD}.Gen
import {MOD}.Gen.Loops
import {MOD}.Sep

/-!
# Each call that the generator followed to its end keeps {TOKEN} solvent

Generated by `scripts/gen_solvent.py` from the success paths of `scripts/gen_paths.py`; do not
edit. Lean checks every statement against `CODE`.

`solvent_<fn>`: a run of `CODE` from pc 0 into `<fn>` that ends with no error, from a state where
the sum of all balances plus the value of the message is at most the ether of the contract
(`Backed message.value`: the message layer has already credited the value), ends in a state where
the sum of all balances is at most the ether of the contract (`Solvent`).

`Sep (callKeys message)` is the hypothesis on keccak of {ROOT}/{DIR}/Sep.lean; it is assumed,
not proved.
-/

set_option autoImplicit false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false
set_option maxRecDepth 4096

namespace {ROOT}

open UsdtVerify
open TokenKit
open {ROOT}.Paths {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic

variable {{fork : Fork}} {{message : Message fork}}
variable {{state : State.TransactionState}} {{substate : Substate}}

"""

TAIL = """  rw [hst]
  clear hst hgas hout hg hsub
  try simp only [mask_idem, storageAt_readSlot] at *
"""


def main():
    tok = tokenlib.load()
    cfg = tok.cfg if hasattr(tok, 'cfg') else json.load(open(sys.argv[1]))
    assert cfg.get('backing') == 'ether', 'gen_solvent.py is for tokens backed by ether'
    d = json.load(open(tok.paths_json))
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, DIR=tok.dir, TOKEN=tok.name)]
    items = []
    for f in tok.funcs:
        items.append((f['name'], [
            "    (hsize : 4 ≤ message.data.size)\n",
            "    (hsize' : message.data.size < 2 ^ 256)\n",
            "    (hsel : selector message.data = 0x%08x)\n" % f['selector']],
            "hfork hsize hsize' hsel"))
    for f in cfg.get('fallbacks', []):
        if f['kind'] == 'short':
            items.append((f['name'], ["    (hsize : message.data.size < 4)\n"], "hfork hsize"))
        else:
            items.append((f['name'], [
                "    (hsize : 4 ≤ message.data.size)\n",
                "    (hsize' : message.data.size < 2 ^ 256)\n",
                "    (hsel : BitVec.ofNat 256 (selector message.data) ∉ ENTRIES.map Prod.fst)\n"],
                "hfork hsize hsize' hsel"))
    done = []
    for fn, hyps, args in items:
        ps = [p for p in d[fn]['paths'] if p['kind'] == 'ok']
        if not ps or any(p['kind'] == 'at' for p in d[fn]['paths']):
            # `stops`: the function ends at a middle frame; its solvency proof is hand-written
            print('Solvent.lean: left out', fn, '(its paths stop at a pc of `stops`: prove it by hand)',
                  file=sys.stderr)
            continue
        done.append(fn)
        o.append('/-- A successful call of `%s` keeps the contract solvent. -/\n' % fn)
        o.append('theorem solvent_%s (hfork : .berlin ≤ fork)\n' % fn)
        o.extend(hyps)
        o.append('    (hsep : Sep (callKeys message))\n')
        o.append('    (hinv : Backed message.value message.currentTarget state)\n')
        o.append('    {gas : Nat} {evm s : Evm fork Nat}\n')
        o.append('    (start : At CODE message 0 [] .empty gas state substate evm)\n')
        o.append('    (hrun : Ends fork evm s) (hok : s.error = none) :\n')
        o.append('    Solvent message.currentTarget s.state := by\n')
        o.append('  have hm1 : bitwiseAnd %s message.caller.toU256 ∈ callKeys message := by\n'
                 '    simp [callKeys]\n' % M)
        o.append('  have hm2 : bitwiseAnd %s (loadWord message.data 4 32) ∈ callKeys message := by\n'
                 '    simp [callKeys]\n' % M)
        o.append('  have hm3 : bitwiseAnd %s (loadWord message.data 36 32) ∈ callKeys message := by\n'
                 '    simp [callKeys]\n' % M)
        o.append('  have hall := ok_%s %s start hrun hok\n' % (fn, args))
        o.append('  clear start hrun hok\n')
        if len(ps) > 1:
            o.append('  rcases hall with %s\n' % ' | '.join(['hall'] * len(ps)))
        for p in ps:
            names = [c[0] for c in p['conds']]
            pat = names + (['hstat', 'hacc'] if p['wrote'] else []) + \
                ['hgas', 'hout', 'hg', 'hst', 'hsub']
            ind = '  '
            if len(ps) > 1:
                o.append('  · obtain ⟨%s⟩ := hall\n' % ', '.join(pat))
                ind = '    '
            else:
                o.append('  obtain ⟨%s⟩ := hall\n' % ', '.join(pat))
            body = [TAIL]
            for i, h in enumerate(names):
                c = p['conds'][i][1]
                if c.startswith('(isZero (isZero (isZero (lessThan ') and \
                        not c.startswith('(isZero (isZero (isZero (lessThan (add '):
                    body.append('  have f%d := Supply.sub_fact_lt %s\n' % (i + 1, h))
            body.append('  unfold Solvent Backed Supply.Solvent Supply.Backed etherOf at *\n')
            body.append('  simp (disch := supply_side) only\n'
                        '    [Supply.sumBal_read, sum_bal hsep, sum_allow hsep, read_bal_allow hsep,\n'
                        '      storageAt_readSlot,\n'
                        '      getAccount_writeSlot, getAccount_readSlot, Supply.add_toNat]\n')
            body.append('  omega\n')
            for line in ''.join(body).splitlines(True):
                o.append(ind + line[2:] if ind != '  ' else line)
        o.append('\n')
    for f in tok.loops:
        fn, sel = f['name'], f['selector']
        done.append(fn)
        o.append('/-- A successful call of `%s` keeps the contract solvent: it only reads. -/\n' % fn)
        o.append('theorem solvent_%s (hfork : .berlin ≤ fork)\n' % fn)
        o.append('    (hsize : 4 ≤ message.data.size)\n')
        o.append('    (hsize\' : message.data.size < 2 ^ 256)\n')
        o.append('    (hsel : selector message.data = 0x%08x)\n' % sel)
        o.append('    (hinv : Backed message.value message.currentTarget state)\n')
        o.append('    {gas : Nat} {evm s : Evm fork Nat}\n')
        o.append('    (start : At CODE message 0 [] .empty gas state substate evm)\n')
        o.append('    (hrun : Ends fork evm s) (hok : s.error = none) :\n')
        o.append('    Solvent message.currentTarget s.state :=\n')
        o.append('  Supply.solvent_of_ro (Loops.ro_%s hfork hsize hsize\' hsel start hrun hok)\n'
                 '    hinv.solvent\n\n' % fn)
    o.append('end %s\n' % tok.root)
    open(os.path.join(tok.lean_dir, 'Solvent.lean'), 'w').write(''.join(o))
    print('Solvent.lean:', ', '.join(done))


main()
