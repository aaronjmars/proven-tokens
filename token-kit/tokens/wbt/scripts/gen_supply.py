#!/usr/bin/env python3
# SUPERSEDED, DO NOT RUN (the ten-token audit, finding WBT-4): this local copy is merged into the kit
# (token-kit/scripts, see kit-status.json wbt_merge) and differs from it. The files of WBT are
# regenerated with the kit: bash token-kit/scripts/regen.sh tokens/wbt/config/wbt.json
"""Write <Root>/<Dir>/Invariant.lean for WBT: for each function the theorem `delta_<fn>` (the sum
of the balances minus the total supply is the same before and after a successful call) and from
it `supply_<fn>` (the invariant is kept), then `delta_step` and `supply_preserved` for every
selector of the table.

A local variant of the kit's scripts/gen_supply.py (mode `checked08`). What differs:
- the checked addition of Solidity 0.8 with the optimizer OFF is `ISZERO (GT a (MAX - v))`
  (lemma `add_fact_submax` of Wbt/Lib.lean); the kit knows only `ISZERO (GT a (NOT v))`;
- each function gets the stronger `delta_<fn>`, with no hypothesis on the start state;
  `supply_<fn>` follows from it.

Usage: gen_supply.py <config/token.json>"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..',
                                'scripts'))
import tokenlib  # noqa: E402

M = '(1461501637330902918203684832716283019655932542975 : U256)'
MAXSUB = '(sub (115792089237316195423570985008687907853269984665640564039457584007913129639935 : U256)'

HEAD = """import {MOD}.Gen
import {MOD}.Gen.Loops
import {MOD}.Sep
import {MOD}.Lib

/-!
# The supply invariant of {TOKEN} is kept by every successful call

Generated by `tokens/{low}/scripts/gen_supply.py` from the success paths of the path generator;
do not edit. Lean checks every statement against `CODE`.

`D` (`Supply.D {bal} {tot}`) is the sum of the balance words of the 2^160 addresses minus the
word of slot {tot} (`_totalSupply`). The invariant `Inv` is `D = 0`.

- `delta_<fn>`: a run of `CODE` from pc 0 with the selector of `<fn>` that ends with no error
  ends with the same `D` it started with, under `Sep (callKeys message)`. Nothing is assumed
  about the start state. So the sum of the balances moves exactly as `_totalSupply` does: it is
  unchanged by every function but `burn` and `destroyBlackFunds`, where both go down by the same
  amount (the readable corollaries of {ROOT}/{DIR}/Readable.lean give the amount).
- `supply_<fn>`: so the run keeps `Inv`.
- `delta_step`, `supply_preserved`: the same for any selector of the table.

`Sep (callKeys message)` is the hypothesis on keccak of {ROOT}/{DIR}/Sep.lean; it is assumed,
not proved.
-/

set_option autoImplicit false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false
set_option maxRecDepth 4096

namespace {ROOT}

open UsdtVerify
open TokenKit
open {ROOT}.Paths {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic

variable {{fork : Fork}} {{message : Message fork}}
variable {{state : State.TransactionState}} {{substate : Substate}}
variable {{bound : Nat}} {{runChild : MessageRunner fork Nat bound}}

"""


def main():
    tok = tokenlib.load()
    d = json.load(open(tok.paths_json))
    sup = tok.cfg.get('supply', {})
    bal, tot = tok.slots['balances'], tok.slots['totalSupply']
    loops = {f['index']: f for f in tok.loops}
    funcs = [f for f in tok.funcs if any(p['kind'] == 'ok' for p in d[f['name']]['paths'])]
    by = {f['index']: f for f in funcs}
    nt = len(tok.table)
    missing = [i for i in range(nt) if i not in by and i not in loops]
    if missing:
        raise SystemExit('gen_supply (wbt): selectors with no theorem: %r' % missing)
    Dt = lambda st: f'Supply.D {bal} {tot} message.currentTarget {st}'
    rules = sup['rules']
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, DIR=tok.dir, TOKEN=tok.name,
                     low=tok.name.lower(), bal=bal, tot=tot)]

    def sig(kind, fn, sel, sep, inv):
        return ('theorem %s_%s (hfork : .berlin ≤ fork)\n' % (kind, fn) +
                '    (hsize\' : message.data.size < 2 ^ 256)\n' +
                '    (hsel : selector message.data = 0x%08x)\n' % sel +
                ('    (hsep : Sep (callKeys message))\n' if sep else '') +
                ('    (hinv : Inv message.currentTarget state)\n' if inv else '') +
                '    {gas : Nat} {evm s : Evm fork Nat}\n'
                '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                '    (hrun : EndsL runChild evm s) (hok : s.error = none) :\n')

    def supply(fn, sel, sep):
        return ('/-- A successful call of `%s` keeps the invariant. -/\n' % fn +
                sig('supply', fn, sel, sep, True) +
                '    Inv message.currentTarget s.state := by\n'
                '  unfold Inv Supply.Inv at hinv ⊢\n'
                '  rw [delta_%s hfork hsize\' hsel %sstart hrun hok]\n'
                '  exact hinv\n\n' % (fn, 'hsep ' if sep else ''))

    for f in funcs:
        fn, sel = f['name'], f['selector']
        ps = [p for p in d[fn]['paths'] if p['kind'] == 'ok']
        o.append('/-- A successful call of `%s` leaves `D` as it was. -/\n' % fn)
        o.append(sig('delta', fn, sel, True, False))
        o.append('    %s = %s := by\n' % (Dt('s.state'), Dt('state')))
        pats = []
        for p in ps:
            names = [c[0] for c in p['conds']]
            pats.append('⟨' + ', '.join(names + (['hstat', 'hacc'] if p['wrote'] else []) +
                                        ['hgas', 'hout', 'hg', 'hst', 'hsub']) + '⟩')
        if len(ps) == 1:
            o.append('  obtain %s :=\n    ok_%s hfork hsize\' hsel start hrun hok\n' % (pats[0], fn))
        else:
            o.append('  rcases ok_%s hfork hsize\' hsel start hrun hok with\n    %s\n'
                     % (fn, ' |\n    '.join(pats)))
        for p in ps:
            L = ['rw [hst]', 'clear hst hgas hout hg hsub start hrun hok',
                 'try simp only [and_mask_comm, mask_idem, storageAt_readSlot] at *']
            for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                     '(loadWord message.data 36 32)']):
                L.append('have hm%d : bitwiseAnd %s %s ∈ callKeys message := by simp [callKeys]'
                         % (i + 1, M, key))
            for i, (h, c, taken) in enumerate(p['conds']):
                if not taken:
                    continue
                if c.startswith('(isZero (lessThan (storageAt '):
                    L.append('have f%d := Supply.sub_fact_lt1 %s' % (i + 1, h))
                elif c.startswith('(isZero (greaterThan (storageAt ') and MAXSUB in c:
                    L.append('have f%d := add_fact_submax %s' % (i + 1, h))
            L += ['first',
                  '  | (with_reducible rfl)',
                  '  | (simp (disch := supply_side) only',
                  '      [%s] <;>' % rules,
                  '     omega)']
            if len(ps) == 1:
                o.append('  ' + '\n  '.join(L) + '\n')
            else:
                o.append('  · ' + '\n    '.join(L) + '\n')
        o.append('\n')
        o.append(supply(fn, sel, True))
    for f in loops.values():
        fn, sel = f['name'], f['selector']
        o.append('/-- A successful call of `%s` leaves `D` as it was: it only reads. -/\n' % fn)
        o.append(sig('delta', fn, sel, False, False))
        o.append('    %s = %s :=\n' % (Dt('s.state'), Dt('state')))
        o.append('  D_congr (fun n => (Loops.ro_%s hfork hsize\' hsel start hrun hok).storage _ n)\n\n' % fn)
        o.append(supply(fn, sel, False))
    for kind, concl, doc in [
            ('delta', '%s = %s' % (Dt('s.state'), Dt('state')),
             'ends with the `D` it started with: the sum of all balances and `_totalSupply` move '
             'by the same amount.'),
            ('supply', 'Inv message.currentTarget s.state',
             'keeps the invariant: if the sum of all balances was `_totalSupply` before, it is '
             'after.')]:
        name = 'delta_step' if kind == 'delta' else 'supply_preserved'
        o.append('/-- From Berlin, a run of `CODE` from pc 0 that ends with no error, with any '
                 'selector,\n' + doc + '\n`hsep` is the hypothesis on keccak (not proved). -/\n')
        o.append('theorem %s (hfork : .berlin ≤ fork)\n' % name +
                 '    (hsize\' : message.data.size < 2 ^ 256)\n'
                 '    (hsep : Sep (callKeys message))\n' +
                 ('    (hinv : Inv message.currentTarget state)\n' if kind == 'supply' else '') +
                 '    {gas : Nat} {evm s : Evm fork Nat}\n'
                 '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
                 '    (hrun : EndsL runChild evm s) (hok : s.error = none) :\n'
                 '    ' + concl + ' := by\n'
                 '  obtain ⟨_, _, i, hi⟩ := ends_ok_dispatch hfork hsize\' start hrun hok\n'
                 '  match i, hi with\n')
        inv = ' hinv' if kind == 'supply' else ''
        for i in range(nt):
            sel = tok.table[i][0]
            o.append('  | ⟨%d, _⟩, hi =>\n    have h : selector message.data = 0x%08x := hi\n' % (i, sel))
            if i in by:
                o.append('    exact %s_%s hfork hsize\' h hsep%s start hrun hok\n' % (kind, by[i]['name'], inv))
            else:
                o.append('    exact %s_%s hfork hsize\' h%s start hrun hok\n' % (kind, loops[i]['name'], inv))
        o.append('  | ⟨n + %d, hn⟩, _ => exact absurd hn (by omega)\n\n' % nt)
    o.append('end %s\n' % tok.root)
    open(os.path.join(tok.lean_dir, 'Invariant.lean'), 'w').write(''.join(o))
    print('Invariant.lean:', len(funcs), 'functions,', len(loops), 'read-only loops')


main()
