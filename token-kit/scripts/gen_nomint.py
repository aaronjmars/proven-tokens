#!/usr/bin/env python3
"""Write <Root>/<Dir>/NoMint.lean (only when the configuration has the key `nomint`; merged from
the local generator of WBT; the texts are for a total supply in slot 5 and a blacklist
mapping, as WBT has): no successful call makes `_totalSupply` larger.

- `total_le`: a run of `CODE` from pc 0 that ends with no error, with any selector, ends with a
  word of slot 5 that is at most the word it started with. It is read off the readable
  corollaries (Readable.lean) and the read-only theorems of name() and symbol() (Gen/Loops.lean).
- `supply_never_grows`: the same along every finite sequence of calls and of changes that keep
  the storage of the contract (`Calls`, Seq.lean).

The table `nomint.kind` of the configuration says where the claim about slot 5 stands among the claims of each readable
corollary; Lean checks each line.

Usage: gen_nomint.py <config/token.json>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tokenlib  # noqa: E402

M = '(1461501637330902918203684832716283019655932542975 : U256)'
# same k: the claim number k of the second group is "every slot keeps its word";
# total k: claim k is "totalSupply after = totalSupply before";
# less k: claim k is "(totalSupply after).toNat = (totalSupply before).toNat - x";
# others k lit: claim k is "every slot but the literal slot `lit` keeps its word";
# black k: claim k is "every slot but the blacklist slot of the first argument keeps its word".
HEAD = """import {MOD}.Readable
import {MOD}.Seq

/-!
# No successful call of {TOKEN} makes the total supply larger

Generated by `{genby}`; do not edit.

The bytecode has no function that mints: among the 22 selectors, only `burn` and
`destroyBlackFunds` write slot 5 (`_totalSupply`), and both write a smaller or equal word.

- `total_le`: from Berlin, a run of `CODE` from pc 0 that ends with no error, with any selector,
  ends with a word of slot 5 that is at most the word of slot 5 at its start, under
  `Sep (callKeys message)` (the hypothesis on keccak of Sep.lean, not proved).
- `supply_never_grows`: so the word of slot 5 never grows along a finite sequence of successful
  calls and of changes that keep the storage of the contract (`Calls` of Seq.lean).

With `inv_calls` (Seq.lean): if the sum of all balances is `_totalSupply` at the start of such a
sequence, it is at its end, and that common number is at most what it was. The tokens that exist
were put in storage by the constructor, which is not part of the runtime code and is not covered
here.
-/

set_option autoImplicit false
set_option linter.unusedVariables false

namespace {ROOT}

open UsdtVerify
open TokenKit
open {ROOT}.Paths {ROOT}.Complete UsdtVerify.Complete UsdtVerify.Gas

open EthLib.Base (Fork U256 Address)
open EthLib.Execution
open EthLib.Execution.Evm
open EthLib.Execution.Evm.Logic

/-- From Berlin, a run of `CODE` from pc 0 that ends with no error, with any selector: the word
of slot 5 (`_totalSupply`) does not grow. `hsep` is the hypothesis on keccak (not proved). -/
theorem total_le {{fork : Fork}} {{message : Message fork}}
    {{state : State.TransactionState}} {{substate : Substate}}
    {{bound : Nat}} {{runChild : MessageRunner fork Nat bound}}
    (hfork : .berlin ≤ fork)
    (hsize' : message.data.size < 2 ^ 256)
    (hsep : Sep (callKeys message))
    {{gas : Nat}} {{evm s : Evm fork Nat}}
    (start : At CODE message 0 [] .empty gas state substate evm)
    (hrun : EndsL runChild evm s) (hok : s.error = none) :
    (storageAt s.state message.currentTarget 5).toNat ≤
      (storageAt state message.currentTarget 5).toNat := by
  have hm2 : bitwiseAnd {M} (loadWord message.data 4 32) ∈ callKeys message := by
    simp [callKeys]
  obtain ⟨_, _, i, hi⟩ := ends_ok_dispatch hfork hsize' start hrun hok
  match i, hi with
"""

TAIL = """
/-- One successful call does not make the word of slot 5 larger. -/
theorem total_le_goodCall {{C : Address}} {{S S' : State.TransactionState}}
    (h : GoodCall C S S') : (storageAt S' C 5).toNat ≤ (storageAt S C 5).toNat := by
  obtain ⟨fork, message, substate, gas, bound, runChild, evm, s, within, hC, hfork, hsize, K,
    start, hrun, hok, rfl⟩ := h
  subst hC
  exact total_le hfork hsize K start ⟨within, hrun⟩ hok

/-- The word of slot 5 (`_totalSupply`) never grows along a finite sequence of successful calls
to `C` and of changes that keep the storage of `C`. Each call carries its own hypothesis on
keccak `Sep (callKeys message)`. -/
theorem supply_never_grows {{C : Address}} {{S S' : State.TransactionState}}
    (h : Calls C S S') : (storageAt S' C 5).toNat ≤ (storageAt S C 5).toNat := by
  induction h with
  | nil => exact Nat.le_refl _
  | call hg _ ih => exact Nat.le_trans ih (total_le_goodCall hg)
  | other hu _ ih => exact Nat.le_trans ih (Nat.le_of_eq (congrArg BitVec.toNat (hu 5)))

end {ROOT}
"""


def main():
    tok = tokenlib.load()
    nm = tok.cfg.get('nomint')
    if nm is None:
        return
    KIND = {k: tuple(v) for k, v in nm['kind'].items()}
    by = {f['index']: f for f in tok.funcs}
    loops = {f['index']: f for f in tok.loops}
    o = [HEAD.format(MOD=tok.mod, ROOT=tok.root, TOKEN=tok.name, genby=nm.get('generated_by', 'scripts/gen_nomint.py'), M=M)]
    nt = len(tok.table)
    for i in range(nt):
        sel = tok.table[i][0]
        o.append('  | ⟨%d, _⟩, hi =>\n    have h : selector message.data = 0x%08x := hi\n' % (i, sel))
        if i in loops:
            o.append('    exact Nat.le_of_eq (congrArg BitVec.toNat\n'
                     '      ((Loops.ro_%s hfork hsize\' h start hrun hok).storage _ 5))\n' % loops[i]['name'])
            continue
        fn = by[i]['name']
        kind, k = KIND[fn]
        sep = tok.cfg['readable'][fn].get('sep', kind in ('total', 'less'))
        proj = 'r' + '.2' * (k - 1) + '.1'
        o.append('    have r := (Readable.%s_readable hfork hsize\' h %sstart hrun hok).2\n'
                 % (fn, 'hsep ' if sep else ''))
        if kind == 'same':
            o.append('    exact Nat.le_of_eq (congrArg BitVec.toNat (%s 5))\n' % proj)
        elif kind == 'total':
            o.append('    exact Nat.le_of_eq (congrArg BitVec.toNat %s)\n' % proj)
        elif kind == 'less':
            o.append('    exact Nat.le_trans (Nat.le_of_eq %s) (Nat.sub_le _ _)\n' % proj)
        elif kind == 'others':
            o.append('    exact Nat.le_of_eq (congrArg BitVec.toNat (%s 5 (by decide)))\n' % proj)
        else:
            o.append('    exact Nat.le_of_eq (congrArg BitVec.toNat\n'
                     '      (%s 5 (fun e => (hsep.black _ hm2).2 e.symm)))\n' % proj)
    o.append('  | ⟨n + %d, hn⟩, _ => exact absurd hn (by omega)\n' % nt)
    o.append(TAIL.format(ROOT=tok.root))
    open(os.path.join(tok.lean_dir, 'NoMint.lean'), 'w').write(''.join(o))
    print('NoMint.lean: total_le over', nt, 'selectors')


main()
