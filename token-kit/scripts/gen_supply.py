def delta_mode(tok, d, sup):
    """Mode `delta` (`"supply": {{"mode": "delta", ...}}`): for a token where some function moves
    the sum of the balances without the total supply (or the reverse). Each function gets the
    exact change of `D` (0 unless `supply.delta.<fn>` gives a term) and the list of slots
    `supply.fixed_slots` that no successful call changes. Every success path is covered."""
    by = {f['index']: f for f in tok.funcs}
    if len(by) != len(tok.table):
        raise SystemExit('supply mode delta: every entry of the table must be a path function')
    bal, tot = tok.slots['balances'], tok.slots['totalSupply']
    fixed = sup.get('fixed_slots', [])
    deltas = sup.get('delta', {})
    Dt = lambda st: f'Supply.D {bal} {tot} message.currentTarget {st}'
    fix = ''.join(f' ∧\n      storageAt s.state message.currentTarget {k} = '
                  f'storageAt state message.currentTarget {k}' for k in fixed)
    o = [DHEAD.format(MOD=tok.mod, ROOT=tok.root, DIR=tok.dir, TOKEN=tok.name, tot=tot,
                      fixed=', '.join(str(k) for k in fixed) or '(none)',
                      deltas='unchanged, but ' + ', '.join(f'`{k}`: plus `{v}`' for k, v in deltas.items())
                      if deltas else 'unchanged')]
    for f in tok.funcs:
        fn, sel = f['name'], f['selector']
        ps = [p for p in d[fn]['paths'] if p['kind'] == 'ok']
        dl = deltas.get(fn)
        o.append('/-- A successful call of `%s`: %s%s. -/\n' % (
            fn, '`D` grows by `%s`' % dl if dl else '`D` is unchanged',
            ', the slots %s keep their word' % ', '.join(str(k) for k in fixed) if fixed else ''))
        o.append('theorem delta_%s (hfork : .berlin ≤ fork)\n' % fn)
        o.append('    (hsize\' : message.data.size < 2 ^ 256)\n')
        o.append('    (hsel : selector message.data = 0x%08x)\n' % sel)
        o.append('    (hsep : Sep (callKeys message))\n')
        o.append('    {gas : Nat} {evm s : Evm fork Nat}\n')
        o.append('    (start : At CODE message 0 [] .empty gas state substate evm)\n')
        o.append('    (hrun : Ends fork evm s) (hok : s.error = none) :\n')
        o.append('    %s = %s%s%s := by\n' % (Dt('s.state'), Dt('state'), ' + ' + dl if dl else '', fix))
        pats = []
        for p in ps:
            names = [c[0] for c in p['conds']]
            pats.append('⟨' + ', '.join(names + (['hstat', 'hacc'] if p['wrote'] else []) +
                                        ['hgas', 'hout', 'hg', 'hst', 'hsub']) + '⟩')
        o.append('  rcases ok_%s hfork hsize\' hsel start hrun hok with\n    %s\n' % (fn, ' | '.join(pats)))
        for p in ps:
            L = ['rw [hst]', 'clear hst hgas hout hg hsub start hrun hok',
                 'try simp only [mask_idem, storageAt_readSlot] at *']
            for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                     '(loadWord message.data 36 32)']):
                L.append('have hm%d : bitwiseAnd %s %s ∈ callKeys message := by simp [callKeys]'
                         % (i + 1, M, key))
            for i, (h, c, taken) in enumerate(p['conds']):
                if not taken:
                    continue
                if c.startswith('(isZero (isZero (isZero (greaterThan '):
                    L.append('have f%d := Supply.sub_fact %s' % (i + 1, h))
                elif c.startswith('(isZero (isZero (isZero (lessThan (add '):
                    L.append('have f%d := Supply.add_fact %s' % (i + 1, h))
            if fixed:
                L.append('refine ⟨?_, ' + ', '.join(['?_'] * len(fixed)) + '⟩')
            dproof = ['first', '  | (simp (disch := supply_side) only',
                      '      [Supply.D_read, D_bal hsep, D_tot hsep, D_allow hsep, storageAt_readSlot]',
                      '     first | done | (generalize %s = d0; omega))' % Dt('state'),
                      '  | (with_reducible rfl)']
            if fixed:
                L.append('· ' + dproof[0])
                L += ['  ' + x for x in dproof[1:]]
                for _ in fixed:
                    L.append('· first')
                    L.append('    | (simp (disch := first | decide | supply_side) only')
                    L.append('        [storageAt_readSlot, keep_bal hsep, keep_allow hsep]; done)')
                    L.append('    | (with_reducible rfl)')
            else:
                L += dproof
            o.append('  · ' + '\n    '.join(L) + '\n')
        o.append('\n')
    movers = [f for f in tok.funcs if f['name'] in deltas]
    alts = [Dt('s.state') + ' = ' + Dt('state')] + [
        '(selector message.data = 0x%08x ∧\n        %s = %s + %s)' % (
            f['selector'], Dt('s.state'), Dt('state'), deltas[f['name']]) for f in movers]
    o.append('/-- From Berlin, a run of `CODE` from pc 0 that ends with no error: `D` is unchanged%s;\n'
             'the slots %s keep their word. `hsep` is the hypothesis on keccak (not proved). -/\n'
             % (''.join(', or the call is `%s` and `D` grows by `%s`' % (f['name'], deltas[f['name']])
                        for f in movers), ', '.join(str(k) for k in fixed) or '(none)'))
    o.append('theorem supply_step (hfork : .berlin ≤ fork)\n'
             '    (hsize\' : message.data.size < 2 ^ 256)\n'
             '    (hsep : Sep (callKeys message))\n'
             '    {gas : Nat} {evm s : Evm fork Nat}\n'
             '    (start : At CODE message 0 [] .empty gas state substate evm)\n'
             '    (hrun : Ends fork evm s) (hok : s.error = none) :\n'
             '    (' + ' ∨\n      '.join(alts) + ')' + fix + ' := by\n'
             '  obtain ⟨_, _, i, hi⟩ := ends_ok_dispatch hfork hsize\' start hrun hok\n'
             '  match i, hi with\n')
    nt = len(tok.table)
    for i in range(nt):
        f = by[i]
        o.append('  | ⟨%d, _⟩, hi =>\n    have h : selector message.data = 0x%08x := hi\n' % (i, f['selector']))
        o.append('    have hd := delta_%s hfork hsize\' h hsep start hrun hok\n' % f['name'])
        k = movers.index(f) + 1 if f in movers else 0
        inj = 'hd.1' if fixed else 'hd'
        if k:
            inj = '⟨h, %s⟩' % inj
        if len(alts) > 1:
            if k < len(alts) - 1:
                inj = 'Or.inl %s' % inj
            for _ in range(k):
                inj = 'Or.inr (%s)' % inj
        o.append('    exact ⟨%s, hd.2⟩\n' % inj if fixed else '    exact %s\n' % inj)
    o.append('  | ⟨n + %d, hn⟩, _ => exact absurd hn (by omega)\n\nend %s\n' % (nt, tok.root))
    open(os.path.join(tok.lean_dir, 'Invariant.lean'), 'w').write(''.join(o))
    print('Invariant.lean (delta):', len(tok.funcs), 'functions,', len(fixed), 'fixed slots')


def top_args(t):
    """The arguments of the application `(f a b ...)` printed by gen_paths.py."""
    assert t[0] == '(' and t[-1] == ')'
    out, depth, cur = [], 0, ''
    for ch in t[1:-1]:
        if ch == ' ' and depth == 0:
            out.append(cur)
            cur = ''
            continue
        depth += ch == '('
        depth -= ch == ')'
        cur += ch
    return out + [cur]


def is_balance_read(c, bal):
    """Whether the condition `(isZero (lessThan (storageAt S C key) v))` reads the balance of an
    address word: `key` is `(mapSlot x (<bal> : U256))` with `x` no mapping slot."""
    lt = top_args(top_args(c)[1])
    rd = top_args(lt[1])
    if rd[0] != 'storageAt' or not rd[3].startswith('(mapSlot '):
        return False
    key = top_args(rd[3])
    return ' '.join(key[2:]) == '(%d : U256)' % bal and '(mapSlot ' not in ' '.join(key[1:2])


def checked08(fn, sel, ps, sup, ENDS):
    """`"supply": {"checked08": true}`: a function of Solidity 0.8 compiled with the optimizer
    on. Every success path is covered (the function can have several); the mask of an address
    on the right of AND is first moved to the left (`and_mask_comm`); a checked subtraction is
    `ISZERO (LT a v)` and a checked addition `ISZERO (GT a (NOT v))`.

    `"supply": {"checked06": true}`: the same proof for Solidity 0.5 and 0.6 with the optimizer
    on (a token in the style of DAI): the facts of the SafeMath checks of that compiler, the
    caller as a key with no mask, and `supply.norm` for the rewrite rules that bring every key
    to one form. With `"require_lt": true` too (the optimizer off, DAI): `require(x >= a)` is
    `ISZERO (LT x a)` and gives the fact of the difference (`Supply.sub_fact_lt1`).

    Switches for Solidity 0.8 code with `unchecked` arithmetic on the balances (SKY; the lemmas
    are in TokenKit/Evm/SupplyUnchecked.lean), all optional: `caller_key: "raw"` (the caller is a
    key with no mask, as with checked06); `norm_disch` (a discharger for the first rewrite, so
    that `norm` can hold conditional rules: the read of the total supply after a write of a
    balance); `unchecked: true` (after `require(balance >= v)`, the fact `Supply.le_D_of_cond`
    that `v` is at most the sum of all balances; the bound of the word of the total supply; and
    the facts of the checked addition `ISZERO (GT a (ADD v a))`)."""
    o = ['/-- A successful call of `%s` keeps the invariant. -/\n' % fn,
         'theorem supply_%s (hfork : .berlin ≤ fork)\n' % fn,
         '    (hsize\' : message.data.size < 2 ^ 256)\n',
         '    (hsel : selector message.data = 0x%08x)\n' % sel,
         '    (hsep : Sep (callKeys message))\n',
         '    (hinv : Inv message.currentTarget state)\n',
         '    {gas : Nat} {evm s : Evm fork Nat}\n',
         '    (start : At CODE message 0 [] .empty gas state substate evm)\n',
         '    (hrun : ' + ENDS + ' evm s) (hok : s.error = none) :\n',
         '    Inv message.currentTarget s.state := by\n']
    pats = []
    for p in ps:
        names = [c[0] for c in p['conds']]
        pats.append('⟨' + ', '.join(names + (['hstat', 'hacc'] if p['wrote'] else []) +
                                    ['hgas', 'hout', 'hg', 'hst', 'hsub']) + '⟩')
    if len(ps) == 1:
        o.append('  obtain %s :=\n    ok_%s hfork hsize\' hsel start hrun hok\n' % (pats[0], fn))
    else:
        o.append('  rcases ok_%s hfork hsize\' hsel start hrun hok with\n    %s\n'
                 % (fn, ' |\n    '.join(pats)))
    rules = sup.get('rules', 'Supply.D_read, D_bal hsep, D_tot hsep, D_allow hsep, '
                             'storageAt_readSlot')
    c06 = sup.get('checked06')
    for p in ps:
        L = ['rw [hst]', 'clear hst hgas hout hg hsub start hrun hok',
             'try simp %sonly [%s] at *' % (
                 '(disch := %s) ' % sup['norm_disch'] if sup.get('norm_disch') else '',
                 sup.get('norm', 'and_mask_comm, mask_idem, storageAt_readSlot'))]
        udict = isinstance(sup.get('unchecked'), dict)   # USDE, ENA: `unchecked_facts`
        if sup.get('unchecked') and not udict:
            L.append('have htot := (storageAt state message.currentTarget %d).isLt' % sup['tot_slot'])
        for i, key in enumerate(['message.caller.toU256', '(loadWord message.data 4 32)',
                                 '(loadWord message.data 36 32)']):
            if (c06 or sup.get('caller_key') == 'raw') and i == 0:
                # the caller is a key as it is: its word has no bit above the address
                L.append('have hm1 : %s ∈ callKeys message := by simp [callKeys]' % key)
                continue
            L.append('have hm%d : bitwiseAnd %s %s ∈ callKeys message := by simp [callKeys]'
                     % (i + 1, M, key))
        for i, (h, c, taken) in enumerate(p['conds']):
            if not taken:
                continue
            if c06:
                # Solidity 0.5 and 0.6 with the optimizer on: `require(a <= x)` is
                # `ISZERO (GT a x)`, the SafeMath sub `ISZERO (GT (SUB x a) x)` and the SafeMath
                # add `ISZERO (LT (ADD x a) x)` (TokenKit/Evm/Opt06.lean)
                if c.startswith('(isZero (greaterThan (sub '):
                    L.append('have f%d := Supply.sub_fact_chk %s' % (i + 1, h))
                elif c.startswith('(isZero (greaterThan '):
                    L.append('have f%d := Supply.sub_fact_gt1 %s' % (i + 1, h))
                elif c.startswith('(isZero (lessThan (add '):
                    L.append('have f%d := Supply.add_fact_lt %s' % (i + 1, h))
                elif sup.get('require_lt') and c.startswith('(isZero (lessThan (storageAt '):
                    # `supply.require_lt` (the optimizer off, DAI): `require(x >= a)` is
                    # `ISZERO (LT x a)`; the check of the sub after it is a branch that
                    # gen_paths.py decides (`sub_after_ge_lt`), so this is the fact left
                    L.append('have f%d := Supply.sub_fact_lt1 %s' % (i + 1, h))
                continue
            if c.startswith('(isZero (lessThan (storageAt '):
                L.append('have f%d := Supply.sub_fact_lt1 %s' % (i + 1, h))
                if sup.get('unchecked') and not udict and is_balance_read(c, sup['bal_slot']):
                    # a `require` on a balance (not on an allowance)
                    L.append('have b%d := Supply.le_D_of_cond (b := %d) (t := %d) %s (by %s)'
                             % (i + 1, sup['bal_slot'], sup['tot_slot'], h,
                                sup.get('norm_disch', 'supply_side')))
            elif c.startswith('(isZero (greaterThan (storageAt ') and '(bitwiseNot ' in c:
                L.append('have f%d := Supply.add_fact_not %s' % (i + 1, h))
            elif udict and c.startswith('(isZero (greaterThan (storageAt ') and '(add ' in c:
                # Solidity 0.8.19 with the optimizer on: the check of `a + v` is
                # `ISZERO (GT a (ADD v a))`
                L.append('have f%d := Supply.add_fact_gtc %s' % (i + 1, h))
            elif sup.get('unchecked') and not udict and c.startswith('(isZero (greaterThan (storageAt '):
                # the checked addition `v + a` of SKY: `ISZERO (GT a (ADD v a))`
                L.append('have f%d := Supply.add_fact_gt %s' % (i + 1, h))
                L.append('have a%d := Supply.add_bound_gt %s' % (i + 1, h))
        if udict:
            L[2:2] = unchecked_facts(p['state'], sup)
            gs = [x.split()[1] for x in L if x.startswith('have g')]
            L += ['unfold %s at hinv ⊢' % sup.get('unfold', 'Inv Supply.Inv'),
                  'first',
                  '  | (with_reducible exact hinv)',
                  '  | (simp (disch := %s) only' % sup.get('disch', 'supply_side'),
                  '      [%s]%s' % (rules, ' at %s ⊢' % ' '.join(gs) if gs else ''),
                  '     omega)']
            if len(ps) == 1:
                o.append('  ' + '\n  '.join(L) + '\n')
            else:
                o.append('  · ' + '\n    '.join(L) + '\n')
            continue
        L += ['unfold %s at hinv ⊢' % sup.get('unfold', 'Inv Supply.Inv'),
              'first',
              '  | (with_reducible exact hinv)',
              '  | (simp (disch := %s) only' % sup.get('disch', 'supply_side'),
              '      [%s]' % rules,
              '     omega)']
        if len(ps) == 1:
            o.append('  ' + '\n  '.join(L) + '\n')
        else:
            o.append('  · ' + '\n    '.join(L) + '\n')
    o.append('\n')
    return ''.join(o)


def sexp(text):
    """The term as nested lists of atoms."""
    toks = re.findall(r'[()]|[^\s()]+', text)
    pos = 0

    def rd():
        nonlocal pos
        t = toks[pos]
        pos += 1
        if t != '(':
            return t
        out = []
        while toks[pos] != ')':
            out.append(rd())
        pos += 1
        return out
    return rd()


def show(t):
    return t if isinstance(t, str) else '(' + ' '.join(show(x) for x in t) + ')'


def unchecked_facts(state, sup):
    """`"supply": {"unchecked": {"balances": b, "totalSupply": t}}`: Solidity from 0.8 with
    `unchecked` blocks (OpenZeppelin ERC20 from 4.8): the balance of the receiver is added to
    with no check, and the total supply is subtracted from with no check, because the invariant
    itself excludes the overflow. For each such word of the end state `state`, one fact `g<i>`:
    if the sum of the balances minus the total supply, in the state the word is read from, is
    at most minus the amount, then the word does not wrap (lemmas `Supply.add_bal_inv` and
    `Supply.sub_tot_inv`). The proof of the path then gets that premise from `hinv`."""
    u = sup['unchecked']
    b, t = ['%d' % u['balances'], ':', 'U256'], ['%d' % u['totalSupply'], ':', 'U256']
    lt = sup.get('key_lt', 'first | exact mask_lt _ | exact mask_ltR _ | exact toNat_toU256_lt _')
    seen, out = [], []

    def walk(x):
        if not isinstance(x, list):
            return
        for y in x:
            walk(y)
        if len(x) == 3 and x[0] == 'add' and isinstance(x[2], list) and x[2][0] == 'storageAt' \
                and isinstance(x[2][3], list) and x[2][3][0] == 'mapSlot' and x[2][3][2] == b:
            fact = ('Supply.add_bal_inv (b := %s) (t := %s) (C := %s) (S := %s) (x := %s) (v := %s) '
                    '(by %s)' % (show(b), show(t), show(x[2][2]), show(x[2][1]), show(x[2][3][1]),
                                 show(x[1]), lt))
        elif len(x) == 3 and x[0] == 'sub' and isinstance(x[1], list) and x[1][0] == 'storageAt' \
                and x[1][3] == t:
            fact = ('Supply.sub_tot_inv (b := %s) (t := %s) (C := %s) (S := %s) (v := %s)'
                    % (show(b), show(t), show(x[1][2]), show(x[1][1]), show(x[2])))
        else:
            return
        if fact not in seen:
            seen.append(fact)
            out.append('have g%d := %s' % (len(seen), fact))
    walk(sexp(state))
    return out


